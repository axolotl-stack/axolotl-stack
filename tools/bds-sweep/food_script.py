"""Print tools/bds-sweep/scripts/foods.txt: every vanilla food eaten once
(suspicious stew for each data value), each from no saturation and a food
level that leaves room for its nutrition:

    python tools/bds-sweep/food_script.py > tools/bds-sweep/scripts/foods.txt
    python tools/bds-sweep/food_script.py --foods dried_kelp*2,chicken*6,poisonous_potato*4,rotten_flesh*3,suspicious_stew:5 \
        --saturation-probe > tools/bds-sweep/scripts/foods-2.txt

`--foods` eats the listed foods instead (`item[:data][*count]`), and
`--saturation-probe` then drains to food 10 and gives the Saturation effect
for a second at amplifiers 0 and 1.

The drains are planned by simulating BDS's exhaustion (4 per point, from
saturation first, a fraction of saturation costing a whole point) with the
food documents' nutrition and saturation levels; the replay starts every food
from the values BDS really had (`food_table.py`)."""
import argparse
import math
import sys

sys.stdout.reconfigure(newline='\n')
LEVELS = {'poor': 0.1, 'low': 0.3, 'normal': 0.6, 'good': 0.8, 'max': 1.0, 'supernatural': 1.2}
# (item, data, nutrition, saturation level, use ticks): the planning values of
# the behaviour pack's food documents; the replay reads BDS's own values.
FOODS = [
    ('apple', 0, 4, 0.3, 32), ('baked_potato', 0, 5, 'normal', 32), ('beef', 0, 3, 'low', 32),
    ('beetroot', 0, 1, 'normal', 32), ('beetroot_soup', 0, 6, 'normal', 32), ('bread', 0, 5, 'normal', 32),
    ('carrot', 0, 3, 'normal', 32), ('chicken', 0, 2, 'low', 32), ('cod', 0, 2, 'poor', 32),
    ('cooked_beef', 0, 8, 'good', 32), ('cooked_chicken', 0, 6, 'normal', 32), ('cooked_cod', 0, 5, 'normal', 32),
    ('cooked_mutton', 0, 6, 'good', 32), ('cooked_porkchop', 0, 8, 'good', 32), ('cooked_rabbit', 0, 5, 'normal', 32),
    ('cooked_salmon', 0, 6, 'good', 32), ('cookie', 0, 2, 'poor', 32), ('dried_kelp', 0, 1, 'poor', 32),
    ('enchanted_golden_apple', 0, 4, 'supernatural', 32), ('glow_berries', 0, 2, 'low', 32),
    ('golden_apple', 0, 4, 'supernatural', 32), ('golden_carrot', 0, 6, 'supernatural', 32),
    ('honey_bottle', 0, 6, 'poor', 40), ('melon_slice', 0, 2, 'low', 32), ('mushroom_stew', 0, 6, 'normal', 32),
    ('mutton', 0, 2, 'low', 32), ('poisonous_potato', 0, 2, 'low', 32), ('porkchop', 0, 3, 'low', 32),
    ('potato', 0, 1, 'low', 32), ('pufferfish', 0, 1, 'poor', 32), ('pumpkin_pie', 0, 8, 'low', 32),
    ('rabbit', 0, 3, 'low', 32), ('rabbit_stew', 0, 10, 'normal', 32), ('rotten_flesh', 0, 4, 'poor', 32),
    ('salmon', 0, 2, 'poor', 32), ('spider_eye', 0, 2, 'good', 32), ('sweet_berries', 0, 2, 'low', 32),
    ('tropical_fish', 0, 1, 'poor', 32),
] + [('suspicious_stew', data, 6, 'normal', 32) for data in range(14)] + [
    # Last: it teleports the player.
    ('chorus_fruit', 0, 4, 'low', 32),
]
DRAIN_AMPLIFIER = 63          # 0.32 exhaustion per tick: 1.6 food points per second
POINTS_PER_SECOND = 0.005 * (DRAIN_AMPLIFIER + 1) * 20 / 4

parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument('--foods', help='item[:data][*count],... instead of every food')
parser.add_argument('--saturation-probe', action='store_true')
args = parser.parse_args()
plan = FOODS
script_name = 'foods.txt'
if args.foods:
    known = {(item, data): row for row in FOODS for item, data in [row[:2]]}
    plan = []
    for spec in args.foods.split(','):
        spec, _, count = spec.partition('*')
        item, _, data = spec.partition(':')
        plan += [known[(item, int(data or 0))]] * int(count or 1)
    script_name = 'foods-2.txt'
    title = 'Foods eaten again: ' + args.foods.replace('*', ' x').replace(',', ', ')
    if args.saturation_probe:
        title += ', then the Saturation effect at food 10'
else:
    title = 'Every vanilla food eaten once (suspicious stew for each data value 0-13)'

print(f'''# {title},
# against BDS: `python tools/bds-sweep/script.py tools/bds-sweep/scripts/{script_name} --out DIR`.
# Generated by tools/bds-sweep/food_script.py: before each food a Hunger effect
# (amplifier 63, 1.6 food points a second) drains the saturation and enough
# food that the food's nutrition fits, then the food is given (hotbar slot 0)
# and used once; BDS finishes eating it. Effects are cleared after each one;
# the honey bottle is drunk with Poison on. The difficulty is easy: in the
# peaceful world script.py makes, the food level never drops. Ticks are
# the client's inputs.
#
# Arena as in breaking.txt: a stone floor at y=-61, the player at
# (0.5,-60,0.5) facing east.
20 /gamerule sendcommandfeedback false
21 /gamerule domobspawning false
22 /gamerule dodaylightcycle false
23 /gamerule randomtickspeed 0
24 /time set 6000
25 /fill -4 -61 -4 4 -61 4 stone
26 /fill -4 -60 -4 4 -55 4 air
27 /gamemode survival @s
28 /clear @s
29 /tp @s 0.5 -60 0.5 -90 0
30 /effect @s clear
31 /difficulty easy''')


def drain(food, saturation, exhaustion, target):
    """Seconds of draining that take `(food, saturation)` to no saturation
    and at most `target` food, and the values after."""
    points = math.ceil(saturation) + max(0, food - target)
    seconds = math.ceil(points / POINTS_PER_SECOND)
    exhaustion += POINTS_PER_SECOND * 4 * seconds
    while exhaustion >= 4:
        exhaustion -= 4
        if saturation > 0:
            saturation = max(0.0, saturation - 1)
        else:
            food -= 1
    return seconds, food, saturation, exhaustion


food, saturation, exhaustion = 20, 5.0, 0.0
tick = 50
for item, data, nutrition, level, use_ticks in plan:
    modifier = LEVELS.get(level, level)
    seconds, food, saturation, exhaustion = drain(food, saturation, exhaustion, 20 - nutrition - 1)
    label = item if data == 0 and item != 'suspicious_stew' else f'{item} {data}'
    print(f'\n# {label}')
    if seconds > 0:
        print(f'{tick} /effect @s hunger {seconds} {DRAIN_AMPLIFIER} true')
        tick += 20 * seconds + 5
    print(f'{tick} /effect @s clear')
    print(f'{tick + 1} /clear @s')
    print(f'{tick + 2} /give @s {item} 1 {data}')
    if item == 'honey_bottle':
        print(f'{tick + 3} /effect @s poison 20 0 true')
    print(f'{tick + 5} use')
    food = min(20, food + nutrition)
    saturation = min(saturation + nutrition * modifier * 2, food)
    tick += 5 + use_ticks + 8
    print(f'{tick} /effect @s clear')
    if item == 'chorus_fruit':
        print(f'{tick + 1} /tp @s 0.5 -60 0.5 -90 0')
    tick += 5
    assert food >= 0, (item, food)
if args.saturation_probe:
    for amplifier in (0, 1):
        seconds, food, saturation, exhaustion = drain(food, saturation, exhaustion, 10)
        print(f'\n# The Saturation effect, amplifier {amplifier}, for a second at food 10')
        print(f'{tick} /effect @s hunger {seconds} {DRAIN_AMPLIFIER} true')
        tick += 20 * seconds + 5
        print(f'{tick} /effect @s clear')
        print(f'{tick + 5} /effect @s saturation 1 {amplifier} true')
        print(f'{tick + 40} /effect @s clear')
        tick += 45
        food, saturation = 20, 20.0
print(f'{tick + 10} exit')
print(f'# planned end state: food {food}, saturation {saturation:.1f}', file=sys.stderr)
