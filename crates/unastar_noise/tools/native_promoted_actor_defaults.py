"""Emit java_data/native_promoted_actor_defaults.rs from a native FULL capture.

Input: the JSON written by `NativePendingActorProbe <runtime> <out> --full-boundary`.
Each registered actor block is placed as a pending ProtoChunk marker, then the
chunk is promoted by an actual native FULL request. The saved LevelChunk actor
is the native constructor default for the block's *current* state.

Coordinates and `keepPacked` are removed: the runtime inserts the actor's own
position, and LevelChunk saves add `keepPacked` at the save boundary. Blocks
whose native factory returns null are absent from the table.

Usage: python native_promoted_actor_defaults.py <capture.json> <output.rs>
"""

import hashlib
import json
import struct
import sys

KINDS = {"Byte": 1, "Short": 2, "Int": 3, "Long": 4, "Float": 5, "Double": 6,
         "ByteArray": 7, "Str": 8, "List": 9, "Compound": 10, "IntArray": 11, "LongArray": 12}
PINS = {"server_sha1": "64bb6d763bed0a9f1d632ec347938594144943ed",
        "inner_sha256": "ec47239a8de246335e1d54f6ac319bd35641778eb4b6a6da06372840d02fcebc"}


def modified_utf8(text):
    units = text.encode("utf-16-be")
    out = bytearray()
    for i in range(0, len(units), 2):
        unit = int.from_bytes(units[i:i + 2], "big")
        if 1 <= unit <= 127:
            out.append(unit)
        elif unit <= 2047:
            out += bytes([0xC0 | unit >> 6, 0x80 | unit & 63])
        else:
            out += bytes([0xE0 | unit >> 12, 0x80 | unit >> 6 & 63, 0x80 | unit & 63])
    return struct.pack(">H", len(out)) + out


def payload(tag):
    kind, value = tag["type"], tag["value"]
    if kind == "Byte":
        return struct.pack(">b", value)
    if kind == "Short":
        return struct.pack(">h", value)
    if kind == "Int":
        return struct.pack(">i", value)
    if kind == "Long":
        return struct.pack(">q", value)
    if kind == "Float":
        return struct.pack(">I", value)
    if kind == "Double":
        return struct.pack(">Q", value)
    if kind == "Str":
        return modified_utf8(value)
    if kind in ("ByteArray", "IntArray", "LongArray"):
        code = {"ByteArray": "b", "IntArray": "i", "LongArray": "q"}[kind]
        return struct.pack(">i", len(value)) + b"".join(struct.pack(">" + code, v) for v in value)
    if kind == "List":
        element, items = value
        if any(KINDS[item["type"]] != element for item in items):
            raise ValueError("heterogeneous native list")
        return bytes([element]) + struct.pack(">i", len(items)) + b"".join(payload(item) for item in items)
    if kind == "Compound":
        out = bytearray()
        for name, child in value:
            out.append(KINDS[child["type"]])
            out += modified_utf8(name)
            out += payload(child)
        return bytes(out + b"\0")
    raise ValueError(f"unsupported native tag {kind}")


def main(source, target):
    raw = open(source, "rb").read()
    capture = json.loads(raw)
    if capture.get("failure") or not capture.get("pins_verified") or capture.get("native_tick_count") != 0:
        raise SystemExit("capture is not a successful pinned zero-tick native observation")
    if capture.get("denied_network_attempts"):
        raise SystemExit("capture recorded network attempts")
    entries = {}
    for row in capture["full_boundary_actors"]:
        saved = row["full_saved"]
        if saved is None:
            continue
        if row["full_state"].split("[", 1)[0] != row["block"]:
            raise SystemExit(f"{row['block']}: promotion block changed before save")
        fields = [(name, tag) for name, tag in saved["value"] if name not in ("x", "y", "z", "keepPacked")]
        if row["block"] in entries:
            raise SystemExit(f"{row['block']}: duplicate native observation")
        entries[row["block"]] = bytes([10, 0, 0]) + payload({"type": "Compound", "value": fields})
    lines = [
        "// Native Java 1.21.11 LevelChunk FULL promotion of pending ProtoChunk actors.",
        "// Generated by tools/native_promoted_actor_defaults.py from a NativePendingActorProbe",
        f"// --full-boundary capture SHA256 {hashlib.sha256(raw).hexdigest()};",
        f"// server SHA1 {PINS['server_sha1']}, native code SHA256 {PINS['inner_sha256']}.",
        "// Coordinates and keepPacked are applied at the save boundary. Do not edit.",
        "pub fn promoted_default(block: &str) -> Option<&'static [u8]> {",
        "    Some(match block {",
    ]
    for block in sorted(entries):
        data = entries[block]
        lines.append(f"        {json.dumps(block)} => &[")
        for start in range(0, len(data), 24):
            lines.append("            " + ", ".join(str(b) for b in data[start:start + 24]) + ",")
        lines.append("        ],")
    lines += ["        _ => return None,", "    })", "}", ""]
    with open(target, "w", newline="\n") as out:
        out.write("\n".join(lines))
    print(f"wrote {len(entries)} native promoted actor defaults")


if __name__ == "__main__":
    main(*sys.argv[1:])
