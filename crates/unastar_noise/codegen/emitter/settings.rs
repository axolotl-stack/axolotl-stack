//! Emits `overworld_settings`: the overworld noise settings' scalars, resolved blocks and
//! the legacy blended noise parameters.

use proc_macro2::{Literal, TokenStream};
use quote::quote;
use std::collections::HashMap;

use crate::codegen::data::java_blocks::JavaBlocks;
use crate::codegen::parser::density_function::{DensityFunctionArg, DensityFunctionDef};
use crate::codegen::parser::noise_settings::NoiseSettings;

pub fn emit(
    settings: &NoiseSettings,
    density_functions: &HashMap<String, DensityFunctionArg>,
    blocks: &JavaBlocks,
) -> Result<TokenStream, String> {
    if settings.legacy_random_source {
        return Err("overworld noise settings use the legacy random source".into());
    }
    let base = density_functions
        .get("minecraft:overworld/base_3d_noise")
        .ok_or("density_function/overworld/base_3d_noise.json is missing")?;
    let DensityFunctionArg::Inline(def) = base else {
        return Err("overworld/base_3d_noise is not an inline density function".into());
    };
    let DensityFunctionDef::OldBlendedNoise {
        xz_scale,
        y_scale,
        xz_factor,
        y_factor,
        smear_scale_multiplier,
    } = def.as_ref()
    else {
        return Err("overworld/base_3d_noise is not minecraft:old_blended_noise".into());
    };
    let [xz_scale, y_scale, xz_factor, y_factor, smear] = [
        *xz_scale,
        *y_scale,
        *xz_factor,
        *y_factor,
        *smear_scale_multiplier,
    ]
    .map(Literal::f64_suffixed);

    let resolve = |state: &crate::codegen::parser::noise_settings::BlockStateJson| {
        blocks
            .resolve(&state.name, &state.properties)
            .map(|id| Literal::u32_suffixed(blocks.bedrock(id)))
    };
    let default_block = resolve(&settings.default_block)?;
    let default_fluid = resolve(&settings.default_fluid)?;
    let sea_level = settings.sea_level;
    let min_y = settings.noise.min_y;
    let height = settings.noise.height;
    let cell_width = settings.noise.size_horizontal * 4;
    let cell_height = settings.noise.size_vertical * 4;
    let aquifers = settings.aquifers_enabled;
    let veins = settings.ore_veins_enabled;

    Ok(quote! {
        //! Overworld noise settings (`noise_settings/overworld.json`).
        //! Generated by `codegen/emitter/settings.rs`.

        /// Sea level.
        pub const SEA_LEVEL: i32 = #sea_level;
        /// Lowest block y of the noise volume.
        pub const MIN_Y: i32 = #min_y;
        /// Height of the noise volume in blocks.
        pub const HEIGHT: i32 = #height;
        /// Noise cell width in blocks.
        pub const CELL_WIDTH: i32 = #cell_width;
        /// Noise cell height in blocks.
        pub const CELL_HEIGHT: i32 = #cell_height;
        /// Whether aquifers are enabled.
        pub const AQUIFERS_ENABLED: bool = #aquifers;
        /// Whether ore veins are enabled.
        pub const ORE_VEINS_ENABLED: bool = #veins;
        /// Default block (Bedrock runtime id).
        pub const DEFAULT_BLOCK: u32 = #default_block;
        /// Default fluid (Bedrock runtime id).
        pub const DEFAULT_FLUID: u32 = #default_fluid;

        /// Parameters of the legacy blended terrain noise (`base_3d_noise`).
        #[derive(Debug, Clone, Copy, PartialEq)]
        pub struct BlendedNoiseParams {
            pub xz_scale: f64,
            pub y_scale: f64,
            pub xz_factor: f64,
            pub y_factor: f64,
            pub smear_scale_multiplier: f64,
        }

        /// `overworld/base_3d_noise`.
        pub const BLENDED_NOISE: BlendedNoiseParams = BlendedNoiseParams {
            xz_scale: #xz_scale,
            y_scale: #y_scale,
            xz_factor: #xz_factor,
            y_factor: #y_factor,
            smear_scale_multiplier: #smear,
        };
    })
}
