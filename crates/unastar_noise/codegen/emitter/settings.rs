//! Emits each noise preset's scalars, canonical Java blocks and legacy blended noise
//! parameters into its own settings module.

use proc_macro2::{Literal, TokenStream};
use quote::quote;
use std::collections::HashMap;

use crate::codegen::data::java_blocks::JavaBlocks;
use crate::codegen::parser::density_function::{DensityFunctionArg, DensityFunctionDef};
use crate::codegen::parser::noise_settings::{
    ClimateParameter, DimensionType, NoiseSettings, SpawnTargetPoint,
};

pub fn emit(
    preset: &str,
    settings: &NoiseSettings,
    dimension: &DimensionType,
    density_functions: &HashMap<String, DensityFunctionArg>,
    blocks: &JavaBlocks,
) -> Result<TokenStream, String> {
    let base_name = format!("minecraft:{preset}/base_3d_noise");
    let base = density_functions
        .get(&base_name)
        .ok_or_else(|| format!("density function {base_name} is missing"))?;
    let DensityFunctionArg::Inline(def) = base else {
        return Err(format!("{base_name} is not an inline density function"));
    };
    let DensityFunctionDef::OldBlendedNoise {
        xz_scale,
        y_scale,
        xz_factor,
        y_factor,
        smear_scale_multiplier,
    } = def.as_ref()
    else {
        return Err(format!("{base_name} is not minecraft:old_blended_noise"));
    };
    let [xz_scale, y_scale, xz_factor, y_factor, smear] = [
        *xz_scale,
        *y_scale,
        *xz_factor,
        *y_factor,
        *smear_scale_multiplier,
    ]
    .map(Literal::f64_suffixed);

    let resolve = |state: &crate::codegen::parser::noise_settings::BlockStateJson| {
        blocks
            .resolve(&state.name, &state.properties)
            .map(Literal::u32_suffixed)
    };
    let default_block = resolve(&settings.default_block)?;
    let default_fluid = resolve(&settings.default_fluid)?;
    let sea_level = settings.sea_level;
    let min_y = settings.noise.min_y;
    let height = settings.noise.height;
    let world_min_y = dimension.min_y;
    let world_height = dimension.height;
    let has_skylight = dimension.has_skylight;
    let cell_width = settings.noise.size_horizontal * 4;
    let cell_height = settings.noise.size_vertical * 4;
    let aquifers = settings.aquifers_enabled;
    let veins = settings.ore_veins_enabled;
    let legacy_random_source = settings.legacy_random_source;
    let disable_mob_generation = settings.disable_mob_generation;
    let module_doc = format!("Noise settings (`noise_settings/{preset}.json`).");
    let blended_doc = format!("`{base_name}`.");
    let spawn_target = spawn_target(&settings.spawn_target)?;
    let spawn_target_len = spawn_target.len();
    let spawn_target = spawn_target.iter().map(|point| {
        let dims = point.iter().map(|[min, max]| quote! { [#min, #max] });
        quote! { [#(#dims),*] }
    });

    Ok(quote! {
        #![doc = #module_doc]
        //! Generated by `codegen/emitter/settings.rs`.

        /// Sea level.
        pub const SEA_LEVEL: i32 = #sea_level;
        /// Lowest block y of the noise volume.
        pub const MIN_Y: i32 = #min_y;
        /// Height of the noise volume in blocks.
        pub const HEIGHT: i32 = #height;
        /// Lowest legal build/storage block y (`dimension_type`, not the noise volume).
        pub const WORLD_MIN_Y: i32 = #world_min_y;
        /// Build/storage height in blocks (`dimension_type.height`, not `logical_height`).
        pub const WORLD_HEIGHT: i32 = #world_height;
        /// Whether the dimension has a sky light engine (`dimension_type.has_skylight`).
        pub const HAS_SKYLIGHT: bool = #has_skylight;
        /// Noise cell width in blocks.
        pub const CELL_WIDTH: i32 = #cell_width;
        /// Noise cell height in blocks.
        pub const CELL_HEIGHT: i32 = #cell_height;
        /// Whether aquifers are enabled.
        pub const AQUIFERS_ENABLED: bool = #aquifers;
        /// Whether ore veins are enabled.
        pub const ORE_VEINS_ENABLED: bool = #veins;
        /// Whether the preset uses Java's legacy random source.
        pub const LEGACY_RANDOM_SOURCE: bool = #legacy_random_source;
        /// Whether the preset disables generation-time mob spawning.
        pub const DISABLE_MOB_GENERATION: bool = #disable_mob_generation;
        /// Default block (canonical Java state id).
        pub const DEFAULT_BLOCK: u32 = #default_block;
        /// Default fluid (canonical Java state id).
        pub const DEFAULT_FLUID: u32 = #default_fluid;
        /// Climate points the world spawn search aims for: quantized `[min, max]` per
        /// dimension (temperature, humidity, continentalness, erosion, depth, weirdness,
        /// offset).
        pub const SPAWN_TARGET: [[[i64; 2]; 7]; #spawn_target_len] = [#(#spawn_target),*];

        /// Parameters of the legacy blended terrain noise (`base_3d_noise`).
        #[derive(Debug, Clone, Copy, PartialEq)]
        pub struct BlendedNoiseParams {
            pub xz_scale: f64,
            pub y_scale: f64,
            pub xz_factor: f64,
            pub y_factor: f64,
            pub smear_scale_multiplier: f64,
        }

        #[doc = #blended_doc]
        pub const BLENDED_NOISE: BlendedNoiseParams = BlendedNoiseParams {
            xz_scale: #xz_scale,
            y_scale: #y_scale,
            xz_factor: #xz_factor,
            y_factor: #y_factor,
            smear_scale_multiplier: #smear,
        };
    })
}

/// Quantized `spawn_target` points (Java's `(long)(value * 10000.0F)`).
pub(crate) fn spawn_target(points: &[SpawnTargetPoint]) -> Result<Vec<[[i64; 2]; 7]>, String> {
    let quantize = |n: &serde_json::Number| -> Result<i64, String> {
        let value: f32 = n
            .to_string()
            .parse()
            .map_err(|e| format!("spawn_target value {n}: {e}"))?;
        Ok((value * 10000.0f32) as i64)
    };
    let span = |p: &ClimateParameter| -> Result<[i64; 2], String> {
        Ok(match p {
            ClimateParameter::Point(v) => [quantize(v)?; 2],
            ClimateParameter::Span([min, max]) => [quantize(min)?, quantize(max)?],
        })
    };
    points
        .iter()
        .map(|p| {
            Ok([
                span(&p.temperature)?,
                span(&p.humidity)?,
                span(&p.continentalness)?,
                span(&p.erosion)?,
                span(&p.depth)?,
                span(&p.weirdness)?,
                [quantize(&p.offset)?; 2],
            ])
        })
        .collect()
}
