pub fn emit_noise_params(
    output_dir: &Path,
    package: &str,
    noises: &HashMap<String, NoiseParams>,
) -> Result<(), Box<dyn std::error::Error>> {
    let mut names: Vec<_> = noises.keys().collect();
    names.sort();

    let mut content = String::new();
    writeln!(
        content,
        "// Code generated by unastar_noise. DO NOT EDIT.\npackage {}\n",
        package
    )?;

    writeln!(content, "type NoiseRef int\n")?;
    writeln!(content, "const (")?;
    for (idx, name) in names.iter().enumerate() {
        let const_name = noise_name_to_go_const(name);
        if idx == 0 {
            writeln!(content, "\t{} NoiseRef = iota", const_name)?;
        } else {
            writeln!(content, "\t{}", const_name)?;
        }
    }
    writeln!(content, ")\n")?;

    writeln!(content, "var NoiseParams = []NoiseParamsData{{")?;
    for name in &names {
        let params = noises.get(*name).unwrap();
        let amps = params
            .amplitudes
            .iter()
            .map(|amp| fmt_float(*amp))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            content,
            "\t{{FirstOctave: {}, Amplitudes: []float64{{{}}}}},",
            params.first_octave, amps
        )?;
    }
    writeln!(content, "}}")?;

    std::fs::write(output_dir.join("generated_noise_params.go"), content)?;
    Ok(())
}

pub fn emit_overworld_graph(
    output_dir: &Path,
    package: &str,
    graph: &DependencyGraph,
) -> Result<(), Box<dyn std::error::Error>> {
    let emitter = GoGraphEmitter::new(graph);
    std::fs::write(
        output_dir.join("generated_overworld_graph.go"),
        emitter.emit(package)?,
    )?;
    Ok(())
}

struct GoGraphEmitter<'a> {
    graph: &'a DependencyGraph,
    sorted: Vec<NodeId>,
    node_index: HashMap<NodeId, usize>,
    ref_index: HashMap<String, usize>,
}

impl<'a> GoGraphEmitter<'a> {
    fn new(graph: &'a DependencyGraph) -> Self {
        let sorted: Vec<NodeId> = graph.topo_sort().into_iter().cloned().collect();
        let mut node_index = HashMap::with_capacity(sorted.len());
        let mut ref_index = HashMap::new();

        for (idx, id) in sorted.iter().enumerate() {
            node_index.insert(id.clone(), idx);
            if let Some(node) = graph.nodes.get(id)
                && let Some(name) = &node.ref_name
            {
                ref_index.entry(name.clone()).or_insert(idx);
            }
        }

        Self {
            graph,
            sorted,
            node_index,
            ref_index,
        }
    }

    fn emit(&self, package: &str) -> Result<String, std::fmt::Error> {
        let mut flat_cache_slots = vec![-1isize; self.sorted.len()];
        let mut cache_2d_slots = vec![-1isize; self.sorted.len()];
        let mut flat_cache_order = Vec::new();
        let mut cache_2d_order = Vec::new();

        for (idx, id) in self.sorted.iter().enumerate() {
            let node = self.graph.nodes.get(id).unwrap();
            if node.is_flat_cache {
                flat_cache_slots[idx] = flat_cache_order.len() as isize;
                flat_cache_order.push(idx);
            }
            if node.is_cache_2d {
                cache_2d_slots[idx] = cache_2d_order.len() as isize;
                cache_2d_order.push(idx);
            }
        }

        let mut inner_to_cache_2d = vec![-1isize; self.sorted.len()];
        for id in &self.sorted {
            let node = self.graph.nodes.get(id).unwrap();
            if node.is_cache_2d
                && let Some(inner) = node.dependencies.first()
                && let Some(inner_idx) = self.node_index.get(inner)
            {
                inner_to_cache_2d[*inner_idx] = *self.node_index.get(id).unwrap() as isize;
            }
        }

        let mut roots: Vec<_> = self.graph.roots.iter().collect();
        roots.sort_by_key(|(name, _)| name.as_str());

        let mut content = String::new();
        writeln!(
            content,
            "// Code generated by unastar_noise. DO NOT EDIT.\npackage {}\n",
            package
        )?;

        writeln!(content, "const (")?;
        for (name, id) in &roots {
            let idx = self.node_index.get(*id).copied().unwrap_or_default();
            writeln!(
                content,
                "\t{} = {}",
                root_name_to_const(name),
                idx
            )?;
        }
        writeln!(content, ")\n")?;

        writeln!(content, "var OverworldRoots = map[string]int{{")?;
        for (name, id) in &roots {
            let idx = self.node_index.get(*id).copied().unwrap_or_default();
            writeln!(content, "\t\"{}\": {},", name, idx)?;
        }
        writeln!(content, "}}\n")?;

        writeln!(content, "var OverworldGraph = &Graph{{")?;
        writeln!(content, "\tNodes: []Node{{")?;
        for id in &self.sorted {
            let node = self.graph.nodes.get(id).unwrap();
            writeln!(content, "\t\t{},", self.emit_node_literal(node))?;
        }
        writeln!(content, "\t}},")?;

        writeln!(
            content,
            "\tFlatCacheSlots: []int{{{}}},",
            emit_int_list(&flat_cache_slots)
        )?;
        writeln!(
            content,
            "\tCache2DSlots: []int{{{}}},",
            emit_int_list(&cache_2d_slots)
        )?;
        writeln!(
            content,
            "\tInnerToCache2D: []int{{{}}},",
            emit_int_list(&inner_to_cache_2d)
        )?;
        writeln!(
            content,
            "\tFlatCacheOrder: []int{{{}}},",
            emit_usize_list(&flat_cache_order)
        )?;
        writeln!(
            content,
            "\tCache2DOrder: []int{{{}}},",
            emit_usize_list(&cache_2d_order)
        )?;
        writeln!(content, "}}")?;

        Ok(content)
    }

    fn emit_node_literal(&self, node: &DensityNode) -> String {
        let dep0 = self.dep_index(node, 0);
        let dep1 = self.dep_index(node, 1);
        let dep2 = self.dep_index(node, 2);

        let mut fields = vec![
            format!("Op: {}", op_name(&node.def)),
            format!("Dep0: {}", dep0),
            format!("Dep1: {}", dep1),
            format!("Dep2: {}", dep2),
        ];

        match &node.def {
            DensityFunctionDef::Constant { argument } => {
                fields.push(format!("Const: {}", fmt_float(*argument)));
            }
            DensityFunctionDef::Clamp { min, max, .. }
            | DensityFunctionDef::RangeChoice {
                min_inclusive: min,
                max_exclusive: max,
                ..
            } => {
                fields.push(format!("Min: {}", fmt_float(*min)));
                fields.push(format!("Max: {}", fmt_float(*max)));
            }
            DensityFunctionDef::YClampedGradient {
                from_y,
                to_y,
                from_value,
                to_value,
            } => {
                fields.push(format!("FromY: {}", from_y));
                fields.push(format!("ToY: {}", to_y));
                fields.push(format!("FromValue: {}", fmt_float(*from_value)));
                fields.push(format!("ToValue: {}", fmt_float(*to_value)));
            }
            DensityFunctionDef::Noise {
                noise,
                xz_scale,
                y_scale,
            } => {
                fields.push(format!("Noise: {}", noise_name_to_go_const(noise)));
                fields.push(format!("XZScale: {}", fmt_float(*xz_scale)));
                fields.push(format!("YScale: {}", fmt_float(*y_scale)));
            }
            DensityFunctionDef::ShiftedNoise {
                noise,
                xz_scale,
                y_scale,
                ..
            } => {
                fields.push(format!("Noise: {}", noise_name_to_go_const(noise)));
                fields.push(format!("XZScale: {}", fmt_float(*xz_scale)));
                fields.push(format!("YScale: {}", fmt_float(*y_scale)));
            }
            DensityFunctionDef::WeirdScaledSampler {
                noise,
                rarity_value_mapper,
                ..
            } => {
                fields.push(format!("Noise: {}", noise_name_to_go_const(noise)));
                fields.push(format!(
                    "Rarity: {}",
                    if rarity_value_mapper == "type_1" {
                        "RarityType1"
                    } else {
                        "RarityType2"
                    }
                ));
            }
            DensityFunctionDef::ShiftA { argument }
            | DensityFunctionDef::ShiftB { argument }
            | DensityFunctionDef::Shift { argument } => {
                fields.push(format!("Noise: {}", noise_name_to_go_const(argument)));
            }
            DensityFunctionDef::OldBlendedNoise {
                xz_scale,
                y_scale,
                xz_factor,
                y_factor,
                smear_scale_multiplier,
            } => {
                fields.push(format!("XZScale: {}", fmt_float(*xz_scale)));
                fields.push(format!("YScale: {}", fmt_float(*y_scale)));
                fields.push(format!("XZFactor: {}", fmt_float(*xz_factor)));
                fields.push(format!("YFactor: {}", fmt_float(*y_factor)));
                fields.push(format!(
                    "SmearScaleMultiplier: {}",
                    fmt_float(*smear_scale_multiplier)
                ));
            }
            DensityFunctionDef::Spline { spline } => {
                fields.push(format!("Spline: {}", self.emit_spline(spline)));
            }
            DensityFunctionDef::FindTopSurface {
                lower_bound,
                cell_height,
                ..
            } => {
                fields.push(format!("LowerBound: {}", lower_bound));
                fields.push(format!("CellHeight: {}", cell_height));
            }
            DensityFunctionDef::Add { .. }
            | DensityFunctionDef::Mul { .. }
            | DensityFunctionDef::Min { .. }
            | DensityFunctionDef::Max { .. }
            | DensityFunctionDef::Abs { .. }
            | DensityFunctionDef::Square { .. }
            | DensityFunctionDef::Cube { .. }
            | DensityFunctionDef::Squeeze { .. }
            | DensityFunctionDef::HalfNegative { .. }
            | DensityFunctionDef::QuarterNegative { .. }
            | DensityFunctionDef::FlatCache { .. }
            | DensityFunctionDef::Cache2D { .. }
            | DensityFunctionDef::CacheOnce { .. }
            | DensityFunctionDef::Interpolated { .. }
            | DensityFunctionDef::BlendAlpha {}
            | DensityFunctionDef::BlendOffset {}
            | DensityFunctionDef::BlendDensity { .. }
            | DensityFunctionDef::EndIslands {}
            | DensityFunctionDef::Invert { .. } => {}
        }

        format!("Node{{{}}}", fields.join(", "))
    }

    fn emit_spline(&self, spline: &SplineDef) -> String {
        let points = spline
            .points
            .iter()
            .map(|point| self.emit_spline_point(point))
            .collect::<Vec<_>>()
            .join(", ");
        format!(
            "&Spline{{Coordinate: {}, Points: []SplinePoint{{{}}}}}",
            self.emit_arg_ref(&spline.coordinate),
            points
        )
    }

    fn emit_spline_point(&self, point: &SplinePoint) -> String {
        format!(
            "SplinePoint{{Location: {}, Derivative: {}, Value: {}}}",
            fmt_float(point.location),
            fmt_float(point.derivative),
            self.emit_spline_value(&point.value)
        )
    }

    fn emit_spline_value(&self, value: &SplineValue) -> String {
        match value {
            SplineValue::Constant(v) => format!("SplineValue{{Const: {}}}", fmt_float(*v)),
            SplineValue::Nested(spline) => {
                format!("SplineValue{{Nested: {}}}", self.emit_spline(spline))
            }
        }
    }

    fn emit_arg_ref(&self, arg: &DensityFunctionArg) -> String {
        match arg {
            DensityFunctionArg::Constant(v) => {
                format!("ArgRef{{Node: -1, Const: {}}}", fmt_float(*v))
            }
            DensityFunctionArg::Reference(name) => match self.ref_index.get(name) {
                Some(idx) => format!("ArgRef{{Node: {}}}", idx),
                None => "ArgRef{Node: -1, Const: 0}".to_string(),
            },
            DensityFunctionArg::Inline(def) => match self.find_node_by_def(def) {
                Some(idx) => format!("ArgRef{{Node: {}}}", idx),
                None => "ArgRef{Node: -1, Const: 0}".to_string(),
            },
        }
    }

    fn find_node_by_def(&self, def: &DensityFunctionDef) -> Option<usize> {
        self.sorted.iter().enumerate().find_map(|(idx, id)| {
            let node = self.graph.nodes.get(id)?;
            (node.def == *def).then_some(idx)
        })
    }

    fn dep_index(&self, node: &DensityNode, dep: usize) -> isize {
        node.dependencies
            .get(dep)
            .and_then(|id| self.node_index.get(id))
            .map(|idx| *idx as isize)
            .unwrap_or(-1)
    }
}

fn emit_int_list(values: &[isize]) -> String {
    values
        .iter()
        .map(|value| value.to_string())
        .collect::<Vec<_>>()
        .join(", ")
}

fn emit_usize_list(values: &[usize]) -> String {
    values
        .iter()
        .map(|value| value.to_string())
        .collect::<Vec<_>>()
        .join(", ")
}

fn root_name_to_const(name: &str) -> String {
    format!("Root{}", snake_to_pascal(name))
}

fn noise_name_to_go_const(name: &str) -> String {
    format!("Noise{}", snake_to_pascal(name.strip_prefix("minecraft:").unwrap_or(name)))
}

fn snake_to_pascal(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_uppercase().chain(chars).collect(),
            }
        })
        .collect()
}

fn op_name(def: &DensityFunctionDef) -> &'static str {
    match def {
        DensityFunctionDef::Constant { .. } => "OpConstant",
        DensityFunctionDef::Add { .. } => "OpAdd",
        DensityFunctionDef::Mul { .. } => "OpMul",
        DensityFunctionDef::Min { .. } => "OpMin",
        DensityFunctionDef::Max { .. } => "OpMax",
        DensityFunctionDef::Clamp { .. } => "OpClamp",
        DensityFunctionDef::Abs { .. } => "OpAbs",
        DensityFunctionDef::Square { .. } => "OpSquare",
        DensityFunctionDef::Cube { .. } => "OpCube",
        DensityFunctionDef::Squeeze { .. } => "OpSqueeze",
        DensityFunctionDef::HalfNegative { .. } => "OpHalfNegative",
        DensityFunctionDef::QuarterNegative { .. } => "OpQuarterNegative",
        DensityFunctionDef::Noise { .. } => "OpNoise",
        DensityFunctionDef::ShiftedNoise { .. } => "OpShiftedNoise",
        DensityFunctionDef::YClampedGradient { .. } => "OpYClampedGradient",
        DensityFunctionDef::FlatCache { .. } => "OpFlatCache",
        DensityFunctionDef::Cache2D { .. } => "OpCache2D",
        DensityFunctionDef::CacheOnce { .. } => "OpCacheOnce",
        DensityFunctionDef::Interpolated { .. } => "OpInterpolated",
        DensityFunctionDef::BlendAlpha { .. } => "OpBlendAlpha",
        DensityFunctionDef::BlendOffset { .. } => "OpBlendOffset",
        DensityFunctionDef::BlendDensity { .. } => "OpBlendDensity",
        DensityFunctionDef::RangeChoice { .. } => "OpRangeChoice",
        DensityFunctionDef::Spline { .. } => "OpSpline",
        DensityFunctionDef::WeirdScaledSampler { .. } => "OpWeirdScaledSampler",
        DensityFunctionDef::ShiftA { .. } => "OpShiftA",
        DensityFunctionDef::ShiftB { .. } => "OpShiftB",
        DensityFunctionDef::Shift { .. } => "OpShift",
        DensityFunctionDef::OldBlendedNoise { .. } => "OpOldBlendedNoise",
        DensityFunctionDef::EndIslands { .. } => "OpEndIslands",
        DensityFunctionDef::Invert { .. } => "OpInvert",
        DensityFunctionDef::FindTopSurface { .. } => "OpFindTopSurface",
    }
}

fn fmt_float(value: f64) -> String {
    let mut s = format!("{:.17}", value);
    while s.contains('.') && s.ends_with('0') {
        s.pop();
    }
    if s.ends_with('.') {
        s.push('0');
    }
    if s == "-0" {
        s = "0".to_string();
    }
    s
}
