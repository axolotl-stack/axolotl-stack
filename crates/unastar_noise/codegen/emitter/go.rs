fn noise_const_name(name: &str) -> String {
    format!("Noise{}", go_pascal_name(name))
}

fn root_const_name(name: &str) -> String {
    format!("Root{}", go_pascal_name(name))
}

fn root_func_name(name: &str) -> String {
    format!("Compute{}", go_pascal_name(name))
}

fn go_pascal_name(name: &str) -> String {
    let trimmed = name.rsplit(':').next().unwrap_or(name);
    let mut out = String::new();
    for part in trimmed.split(|c: char| !c.is_ascii_alphanumeric()) {
        if part.is_empty() {
            continue;
        }
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.push(first.to_ascii_uppercase());
            for ch in chars {
                out.push(ch.to_ascii_lowercase());
            }
        }
    }
    out
}

fn fmt_f64(v: f64) -> String {
    let mut s = format!("{:?}", v);
    if !s.contains('.') && !s.contains('e') && !s.contains('E') {
        s.push_str(".0");
    }
    s
}
