pub fn emit_biome_features(
    output_dir: &Path,
    package: &str,
    biomes: &HashMap<String, BiomeJson>,
) -> Result<(), Box<dyn std::error::Error>> {
    let mut biome_names: Vec<_> = biomes.keys().cloned().collect();
    biome_names.sort();

    let mut out = String::new();
    writeln!(&mut out, "// Code generated by unastar_noise. DO NOT EDIT.")?;
    writeln!(&mut out, "package {}", package)?;
    writeln!(&mut out)?;
    writeln!(
        &mut out,
        "var biomePlacedFeaturesByName = map[string]map[GenerationStep][]string{{"
    )?;
    for biome_name in &biome_names {
        let biome = &biomes[biome_name];
        writeln!(&mut out, "\t{}: {{", go_string_literal(&biome_name))?;

        for step in GenerationStep::ALL {
            let step_idx = step as usize;
            let features = biome.features.get(step_idx).cloned().unwrap_or_default();
            if features.is_empty() {
                continue;
            }

            writeln!(
                &mut out,
                "\t\t{}: []string{{",
                generation_step_const_name(step)
            )?;
            for feature in features {
                writeln!(
                    &mut out,
                    "\t\t\t{},",
                    go_string_literal(biome::strip_minecraft_prefix(&feature))
                )?;
            }
            writeln!(&mut out, "\t\t}},")?;
        }
        writeln!(&mut out, "\t}},")?;
    }
    writeln!(&mut out, "}}")?;
    writeln!(&mut out)?;
    writeln!(&mut out, "var biomeCarversByName = map[string][]string{{")?;
    for biome_name in &biome_names {
        let biome = &biomes[biome_name];
        let carvers = match &biome.carvers {
            biome::StringOrArray::Single(carver) => vec![carver.clone()],
            biome::StringOrArray::Array(carvers) => carvers.clone(),
        };

        if carvers.is_empty() {
            continue;
        }
        writeln!(&mut out, "\t{}: []string{{", go_string_literal(&biome_name))?;
        for carver in carvers {
            writeln!(
                &mut out,
                "\t\t{},",
                go_string_literal(biome::strip_minecraft_prefix(&carver))
            )?;
        }
        writeln!(&mut out, "\t}},")?;
    }
    writeln!(&mut out, "}}")?;

    std::fs::write(output_dir.join("generated_biome_features.go"), out)?;
    Ok(())
}

