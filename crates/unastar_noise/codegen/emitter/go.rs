pub fn emit_noise_params(
    output_dir: &Path,
    package: &str,
    noises: &HashMap<String, NoiseParams>,
) -> Result<(), Box<dyn std::error::Error>> {
    let mut entries: Vec<_> = noises.iter().collect();
    entries.sort_by(|(a, _), (b, _)| a.cmp(b));

    let mut out = String::new();
    writeln!(&mut out, "// Code generated by unastar_noise. DO NOT EDIT.")?;
    writeln!(&mut out, "package {}", package)?;
    writeln!(&mut out)?;
    writeln!(&mut out, "type NoiseRef int")?;
    writeln!(&mut out)?;
    writeln!(&mut out, "const (")?;
    writeln!(
        &mut out,
        "\t{} NoiseRef = iota",
        noise_const_name(entries[0].0)
    )?;
    for (name, _) in entries.iter().skip(1) {
        writeln!(&mut out, "\t{}", noise_const_name(name))?;
    }
    writeln!(&mut out, ")")?;
    writeln!(&mut out)?;
    writeln!(&mut out, "var NoiseParams = []NoiseParamsData{{")?;
    for (_, params) in &entries {
        let amplitudes = params
            .amplitudes
            .iter()
            .map(|v| fmt_f64(*v))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            &mut out,
            "\t{{FirstOctave: {}, Amplitudes: []float64{{{}}}}},",
            params.first_octave, amplitudes
        )?;
    }
    writeln!(&mut out, "}}")?;

    std::fs::write(output_dir.join("generated_noise_params.go"), out)?;
    Ok(())
}

pub fn emit_overworld_graph(
    output_dir: &Path,
    package: &str,
    graph: &DependencyGraph,
) -> Result<(), Box<dyn std::error::Error>> {
    let sorted = topo_sorted_nodes(graph);
    let index_by_id = index_map(&sorted);

    let mut flat_cache_slots = vec![-1isize; sorted.len()];
    let mut cache_2d_slots = vec![-1isize; sorted.len()];
    let mut inner_to_cache_2d = vec![-1isize; sorted.len()];
    let mut flat_cache_order = Vec::new();
    let mut cache_2d_order = Vec::new();

    for (idx, node) in sorted.iter().enumerate() {
        if node.is_flat_cache {
            let slot = flat_cache_order.len();
            flat_cache_slots[idx] = slot as isize;
            flat_cache_order.push(idx as isize);
        }
        if node.is_cache_2d {
            let slot = cache_2d_order.len();
            cache_2d_slots[idx] = slot as isize;
            cache_2d_order.push(idx as isize);
            if let Some(inner) = node.dependencies.first()
                && let Some(inner_idx) = index_by_id.get(inner)
            {
                inner_to_cache_2d[*inner_idx] = idx as isize;
            }
        }
    }

    let roots = sorted_roots(graph);

    let mut out = String::new();
    writeln!(&mut out, "// Code generated by unastar_noise. DO NOT EDIT.")?;
    writeln!(&mut out, "package {}", package)?;
    writeln!(&mut out)?;
    writeln!(&mut out, "const (")?;
    for (name, id) in &roots {
        let idx = *index_by_id
            .get(id)
            .ok_or_else(|| format!("missing root index for {}", name))?;
        writeln!(&mut out, "\t{} = {}", root_const_name(name), idx)?;
    }
    writeln!(&mut out, ")")?;
    writeln!(&mut out)?;
    writeln!(&mut out, "var OverworldRoots = map[string]int{{")?;
    for (name, id) in &roots {
        let idx = *index_by_id
            .get(id)
            .ok_or_else(|| format!("missing root index for {}", name))?;
        writeln!(&mut out, "\t\"{}\": {},", name, idx)?;
    }
    writeln!(&mut out, "}}")?;
    writeln!(&mut out)?;
    writeln!(&mut out, "var OverworldGraph = &Graph{{")?;
    writeln!(&mut out, "\tNodes: []Node{{")?;
    for node in &sorted {
        writeln!(
            &mut out,
            "\t\t{},",
            emit_graph_node_literal(node, &index_by_id)?
        )?;
    }
    writeln!(&mut out, "\t}},")?;
    writeln!(
        &mut out,
        "\tFlatCacheSlots: []int{{{}}},",
        join_isize_slice(&flat_cache_slots)
    )?;
    writeln!(
        &mut out,
        "\tCache2DSlots:   []int{{{}}},",
        join_isize_slice(&cache_2d_slots)
    )?;
    writeln!(
        &mut out,
        "\tInnerToCache2D: []int{{{}}},",
        join_isize_slice(&inner_to_cache_2d)
    )?;
    writeln!(
        &mut out,
        "\tFlatCacheOrder: []int{{{}}},",
        join_isize_slice(&flat_cache_order)
    )?;
    writeln!(
        &mut out,
        "\tCache2DOrder:   []int{{{}}},",
        join_isize_slice(&cache_2d_order)
    )?;
    writeln!(&mut out, "}}")?;

    std::fs::write(output_dir.join("generated_overworld_graph.go"), out)?;
    Ok(())
}

pub fn emit_overworld_compiled(
    output_dir: &Path,
    package: &str,
    graph: &DependencyGraph,
) -> Result<(), Box<dyn std::error::Error>> {
    let mut emitter = GoCompiledEmitter::new(graph)?;

    let final_density = emitter.emit_scalar_root("final_density")?;
    let preliminary_inner = emitter.emit_inner_density_root(
        "preliminary_surface_level",
        "computePreliminarySurfaceLevelInnerDensity",
    )?;
    let preliminary_surface = emitter.emit_preliminary_surface_level()?;
    let final_density_4 = emitter.emit_final_density_4()?;

    let mut out = String::new();
    writeln!(&mut out, "// Code generated by unastar_noise. DO NOT EDIT.")?;
    writeln!(&mut out, "package {}", package)?;
    writeln!(&mut out)?;
    writeln!(&mut out, "import \"math\"")?;
    writeln!(&mut out)?;
    writeln!(&mut out, "{}", final_density)?;
    writeln!(&mut out)?;
    writeln!(&mut out, "{}", preliminary_inner)?;
    writeln!(&mut out)?;
    writeln!(&mut out, "{}", preliminary_surface)?;
    writeln!(&mut out)?;
    writeln!(&mut out, "{}", final_density_4)?;

    std::fs::write(output_dir.join("generated_overworld_compiled.go"), out)?;
    Ok(())
}

