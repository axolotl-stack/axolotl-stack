fn topo_sorted_nodes<'a>(graph: &'a DependencyGraph) -> Vec<&'a DensityNode> {
    graph
        .topo_sort()
        .into_iter()
        .filter_map(|id| graph.nodes.get(id))
        .collect()
}

fn generation_step_const_name(step: GenerationStep) -> &'static str {
    match step {
        GenerationStep::RawGeneration => "GenerationStepRawGeneration",
        GenerationStep::Lakes => "GenerationStepLakes",
        GenerationStep::LocalModifications => "GenerationStepLocalModifications",
        GenerationStep::UndergroundStructures => "GenerationStepUndergroundStructures",
        GenerationStep::SurfaceStructures => "GenerationStepSurfaceStructures",
        GenerationStep::Strongholds => "GenerationStepStrongholds",
        GenerationStep::UndergroundOres => "GenerationStepUndergroundOres",
        GenerationStep::UndergroundDecoration => "GenerationStepUndergroundDecoration",
        GenerationStep::FluidSprings => "GenerationStepFluidSprings",
        GenerationStep::VegetalDecoration => "GenerationStepVegetalDecoration",
        GenerationStep::TopLayerModification => "GenerationStepTopLayerModification",
    }
}

fn go_string_literal(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        for escaped in ch.escape_default() {
            out.push(escaped);
        }
    }
    out.push('"');
    out
}

fn go_raw_string_literal(value: &str) -> Result<String, Box<dyn std::error::Error>> {
    if value.contains('`') {
        return Err("raw Go string literal cannot contain backticks".into());
    }
    Ok(format!("`{}`", value))
}

fn emit_json_registry_map(
    out: &mut String,
    name: &str,
    assets: &HashMap<String, RawJsonAsset>,
) -> Result<(), Box<dyn std::error::Error>> {
    let mut names: Vec<_> = assets.keys().cloned().collect();
    names.sort();

    writeln!(&mut *out, "var {} = map[string]string{{", name)?;
    for key in names {
        let raw = serde_json::to_string(&assets[&key].value)?;
        writeln!(
            &mut *out,
            "\t{}: {},",
            go_string_literal(&key),
            go_string_literal(&raw)
        )?;
    }
    writeln!(&mut *out, "}}")?;
    Ok(())
}

fn emit_binary_registry_map(
    out: &mut String,
    name: &str,
    assets: &HashMap<String, StructureTemplateAsset>,
) -> Result<(), Box<dyn std::error::Error>> {
    let mut names: Vec<_> = assets.keys().cloned().collect();
    names.sort();

    writeln!(&mut *out, "var {} = map[string]string{{", name)?;
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")?;
    for key in names {
        let path = Path::new(&manifest_dir)
            .join("structure_data")
            .join(&assets[&key].relative_path);
        let bytes = std::fs::read(path)?;
        let encoded = base64::engine::general_purpose::STANDARD.encode(bytes);
        writeln!(
            &mut *out,
            "\t{}: {},",
            go_string_literal(&key),
            go_raw_string_literal(&encoded)?
        )?;
    }
    writeln!(&mut *out, "}}")?;
    Ok(())
}

fn index_map(sorted: &[&DensityNode]) -> HashMap<NodeId, usize> {
    sorted
        .iter()
        .enumerate()
        .map(|(idx, node)| (node.id.clone(), idx))
        .collect()
}

fn sorted_roots(graph: &DependencyGraph) -> BTreeMap<String, NodeId> {
    graph
        .roots
        .iter()
        .map(|(name, id)| (name.clone(), id.clone()))
        .collect()
}

fn emit_graph_node_literal(
    node: &DensityNode,
    index_by_id: &HashMap<NodeId, usize>,
) -> Result<String, Box<dyn std::error::Error>> {
    let dep = dep_indices(&node.dependencies, index_by_id);
    let mut fields = vec![
        format!("Op: {}", op_const_name(&node.def)),
        format!("Dep0: {}", dep[0]),
        format!("Dep1: {}", dep[1]),
        format!("Dep2: {}", dep[2]),
    ];

    match &node.def {
        DensityFunctionDef::Constant { argument } => {
            fields.push(format!("Const: {}", fmt_f64(*argument)));
        }
        DensityFunctionDef::Clamp { min, max, .. } => {
            fields.push(format!("Min: {}", fmt_f64(*min)));
            fields.push(format!("Max: {}", fmt_f64(*max)));
        }
        DensityFunctionDef::YClampedGradient {
            from_y,
            to_y,
            from_value,
            to_value,
        } => {
            fields.push(format!("FromY: {}", from_y));
            fields.push(format!("ToY: {}", to_y));
            fields.push(format!("FromValue: {}", fmt_f64(*from_value)));
            fields.push(format!("ToValue: {}", fmt_f64(*to_value)));
        }
        DensityFunctionDef::Noise {
            noise,
            xz_scale,
            y_scale,
        } => {
            fields.push(format!("Noise: {}", noise_const_name(noise)));
            fields.push(format!("XZScale: {}", fmt_f64(*xz_scale)));
            fields.push(format!("YScale: {}", fmt_f64(*y_scale)));
        }
        DensityFunctionDef::ShiftedNoise {
            noise,
            xz_scale,
            y_scale,
            ..
        } => {
            fields.push(format!("Noise: {}", noise_const_name(noise)));
            fields.push(format!("XZScale: {}", fmt_f64(*xz_scale)));
            fields.push(format!("YScale: {}", fmt_f64(*y_scale)));
        }
        DensityFunctionDef::Spline { spline } => {
            let (spline_literal, _) = emit_spline_literal(spline, &node.dependencies, index_by_id)?;
            fields.push(format!("Spline: {}", spline_literal));
        }
        DensityFunctionDef::WeirdScaledSampler {
            noise,
            rarity_value_mapper,
            ..
        } => {
            fields.push(format!("Noise: {}", noise_const_name(noise)));
            fields.push(format!(
                "Rarity: {}",
                if rarity_value_mapper == "type_1" {
                    "RarityType1"
                } else {
                    "RarityType2"
                }
            ));
        }
        DensityFunctionDef::ShiftA { argument }
        | DensityFunctionDef::ShiftB { argument }
        | DensityFunctionDef::Shift { argument } => {
            fields.push(format!("Noise: {}", noise_const_name(argument)));
        }
        DensityFunctionDef::OldBlendedNoise {
            xz_scale,
            y_scale,
            xz_factor,
            y_factor,
            smear_scale_multiplier,
        } => {
            fields.push(format!("XZScale: {}", fmt_f64(*xz_scale)));
            fields.push(format!("YScale: {}", fmt_f64(*y_scale)));
            fields.push(format!("XZFactor: {}", fmt_f64(*xz_factor)));
            fields.push(format!("YFactor: {}", fmt_f64(*y_factor)));
            fields.push(format!(
                "SmearScaleMultiplier: {}",
                fmt_f64(*smear_scale_multiplier)
            ));
        }
        DensityFunctionDef::RangeChoice {
            min_inclusive,
            max_exclusive,
            ..
        } => {
            fields.push(format!("Min: {}", fmt_f64(*min_inclusive)));
            fields.push(format!("Max: {}", fmt_f64(*max_exclusive)));
        }
        DensityFunctionDef::FindTopSurface {
            lower_bound,
            cell_height,
            ..
        } => {
            fields.push(format!("LowerBound: {}", lower_bound));
            fields.push(format!("CellHeight: {}", cell_height));
        }
        DensityFunctionDef::Add { .. }
        | DensityFunctionDef::Mul { .. }
        | DensityFunctionDef::Min { .. }
        | DensityFunctionDef::Max { .. }
        | DensityFunctionDef::Abs { .. }
        | DensityFunctionDef::Square { .. }
        | DensityFunctionDef::Cube { .. }
        | DensityFunctionDef::Squeeze { .. }
        | DensityFunctionDef::HalfNegative { .. }
        | DensityFunctionDef::QuarterNegative { .. }
        | DensityFunctionDef::FlatCache { .. }
        | DensityFunctionDef::Cache2D { .. }
        | DensityFunctionDef::CacheOnce { .. }
        | DensityFunctionDef::Interpolated { .. }
        | DensityFunctionDef::BlendAlpha {}
        | DensityFunctionDef::BlendOffset {}
        | DensityFunctionDef::BlendDensity { .. }
        | DensityFunctionDef::EndIslands {}
        | DensityFunctionDef::Invert { .. } => {}
    }

    Ok(format!("Node{{{}}}", fields.join(", ")))
}

fn emit_spline_literal(
    spline: &SplineDef,
    deps: &[NodeId],
    index_by_id: &HashMap<NodeId, usize>,
) -> Result<(String, usize), Box<dyn std::error::Error>> {
    if deps.is_empty() {
        return Err("spline dependency list is empty".into());
    }

    let coord_idx = *index_by_id
        .get(&deps[0])
        .ok_or_else(|| format!("missing spline coordinate index for {}", deps[0].0))?;

    let mut consumed = 1usize;
    let mut points = Vec::with_capacity(spline.points.len());

    for point in &spline.points {
        let value = match &point.value {
            SplineValue::Constant(v) => format!("SplineValue{{Const: {}}}", fmt_f64(*v)),
            SplineValue::Nested(nested) => {
                let (nested_literal, nested_consumed) =
                    emit_spline_literal(nested, &deps[consumed..], index_by_id)?;
                consumed += nested_consumed;
                format!("SplineValue{{Nested: {}}}", nested_literal)
            }
        };
        points.push(format!(
            "SplinePoint{{Location: {}, Derivative: {}, Value: {}}}",
            fmt_f64(point.location),
            fmt_f64(point.derivative),
            value
        ));
    }

    Ok((
        format!(
            "&Spline{{Coordinate: ArgRef{{Node: {}}}, Points: []SplinePoint{{{}}}}}",
            coord_idx,
            points.join(", ")
        ),
        consumed,
    ))
}

fn dep_indices(deps: &[NodeId], index_by_id: &HashMap<NodeId, usize>) -> [isize; 3] {
    let mut out = [-1isize; 3];
    for (i, dep) in deps.iter().take(3).enumerate() {
        if let Some(idx) = index_by_id.get(dep) {
            out[i] = *idx as isize;
        }
    }
    out
}

struct GoCompiledEmitter<'a> {
    graph: &'a DependencyGraph,
    index_by_id: HashMap<NodeId, usize>,
    flat_slot_by_id: HashMap<NodeId, usize>,
    cache_slot_by_id: HashMap<NodeId, usize>,
    inner_cache_wrapper_by_id: HashMap<NodeId, NodeId>,
    var_names: HashMap<NodeId, String>,
    statements: Vec<String>,
    var_counter: usize,
}

impl<'a> GoCompiledEmitter<'a> {
    fn new(graph: &'a DependencyGraph) -> Result<Self, Box<dyn std::error::Error>> {
        let sorted = topo_sorted_nodes(graph);
        let index_by_id = index_map(&sorted);

        let mut flat_slot_by_id = HashMap::new();
        let mut cache_slot_by_id = HashMap::new();
        let mut inner_cache_wrapper_by_id = HashMap::new();

        for node in &sorted {
            if node.is_flat_cache {
                let slot = flat_slot_by_id.len();
                flat_slot_by_id.insert(node.id.clone(), slot);
            }
            if node.is_cache_2d {
                let slot = cache_slot_by_id.len();
                cache_slot_by_id.insert(node.id.clone(), slot);
                if let Some(inner) = node.dependencies.first() {
                    inner_cache_wrapper_by_id.insert(inner.clone(), node.id.clone());
                }
            }
        }

        Ok(Self {
            graph,
            index_by_id,
            flat_slot_by_id,
            cache_slot_by_id,
            inner_cache_wrapper_by_id,
            var_names: HashMap::new(),
            statements: Vec::new(),
            var_counter: 0,
        })
    }

    fn emit_scalar_root(&mut self, root_name: &str) -> Result<String, Box<dyn std::error::Error>> {
        let root_id = self
            .graph
            .roots
            .get(root_name)
            .ok_or_else(|| format!("missing root {}", root_name))?
            .clone();
        self.reset();
        let expr = self.emit_node(&root_id)?;
        let body = self.render_statements_with_return(&expr);
        Ok(format!(
            "func {}(ctx FunctionContext, noises NoiseSource, flat *FlatCacheGrid, col *ColumnContext) float64 {{\n{}}}\n",
            root_func_name(root_name),
            body
        ))
    }

    fn emit_inner_density_root(
        &mut self,
        root_name: &str,
        func_name: &str,
    ) -> Result<String, Box<dyn std::error::Error>> {
        let root_id = self
            .graph
            .roots
            .get(root_name)
            .ok_or_else(|| format!("missing root {}", root_name))?;
        let root = self
            .graph
            .nodes
            .get(root_id)
            .ok_or_else(|| format!("missing node {}", root_id.0))?;
        let inner = root
            .dependencies
            .first()
            .ok_or_else(|| format!("find_top_surface root {} has no inner density", root_name))?
            .clone();

        self.reset();
        let expr = self.emit_node(&inner)?;
        let body = self.render_statements_with_return(&expr);
        Ok(format!(
            "func {}(ctx FunctionContext, noises NoiseSource, flat *FlatCacheGrid, col *ColumnContext) float64 {{\n{}}}\n",
            func_name, body
        ))
    }

    fn emit_preliminary_surface_level(&mut self) -> Result<String, Box<dyn std::error::Error>> {
        let root_id = self
            .graph
            .roots
            .get("preliminary_surface_level")
            .ok_or("missing root preliminary_surface_level")?;
        let root = self
            .graph
            .nodes
            .get(root_id)
            .ok_or_else(|| format!("missing node {}", root_id.0))?;
        let DensityFunctionDef::FindTopSurface {
            lower_bound,
            cell_height,
            ..
        } = &root.def
        else {
            return Err("preliminary_surface_level is not find_top_surface".into());
        };

        let upper_bound_id = root
            .dependencies
            .get(1)
            .ok_or("preliminary_surface_level missing upper bound dependency")?
            .clone();
        self.reset();
        let upper_expr = self.emit_node(&upper_bound_id)?;

        let mut body = String::new();
        for stmt in &self.statements {
            writeln!(&mut body, "\t{}", stmt)?;
        }
        writeln!(&mut body, "\tupperBound := int(math.Floor({}))", upper_expr)?;
        writeln!(
            &mut body,
            "\treturn FindTopSurface(ctx.BlockX, ctx.BlockZ, {}, upperBound, {}, func(y int) float64 {{",
            lower_bound, cell_height
        )?;
        writeln!(
            &mut body,
            "\t\tinnerCtx := FunctionContext{{BlockX: ctx.BlockX, BlockY: y, BlockZ: ctx.BlockZ}}"
        )?;
        writeln!(
            &mut body,
            "\t\treturn computePreliminarySurfaceLevelInnerDensity(innerCtx, noises, flat, col)"
        )?;
        writeln!(&mut body, "\t}})")?;

        Ok(format!(
            "func ComputePreliminarySurfaceLevel(ctx FunctionContext, noises NoiseSource, flat *FlatCacheGrid, col *ColumnContext) float64 {{\n{}}}\n",
            body
        ))
    }

    fn emit_final_density_4(&mut self) -> Result<String, Box<dyn std::error::Error>> {
        let mut body = String::new();
        writeln!(&mut body, "\treturn [4]float64{{")?;
        for lane in 0..4 {
            writeln!(
                &mut body,
                "\t\tComputeFinalDensity(FunctionContext{{BlockX: ctx.BlockX, BlockY: ctx.BlockY[{}], BlockZ: ctx.BlockZ}}, noises, flat, col),",
                lane
            )?;
        }
        writeln!(&mut body, "\t}}")?;

        Ok(format!(
            "func ComputeFinalDensity4(ctx FunctionContext4, noises NoiseSource, flat *FlatCacheGrid, col *ColumnContext) [4]float64 {{\n{}}}\n",
            body
        ))
    }

    fn reset(&mut self) {
        self.var_names.clear();
        self.statements.clear();
        self.var_counter = 0;
    }

    fn render_statements_with_return(&self, expr: &str) -> String {
        let mut body = String::new();
        for stmt in &self.statements {
            let _ = writeln!(&mut body, "\t{}", stmt);
        }
        let _ = writeln!(&mut body, "\treturn {}", expr);
        body
    }

    fn emit_node(&mut self, id: &NodeId) -> Result<String, Box<dyn std::error::Error>> {
        if let Some(wrapper_id) = self.inner_cache_wrapper_by_id.get(id).cloned() {
            let slot = self
                .cache_slot_by_id
                .get(&wrapper_id)
                .ok_or_else(|| format!("missing cache slot for {}", wrapper_id.0))?;
            return Ok(format!("col.values[{}]", slot));
        }
        if let Some(var) = self.var_names.get(id) {
            return Ok(var.clone());
        }

        let node = self
            .graph
            .nodes
            .get(id)
            .ok_or_else(|| format!("missing node {}", id.0))?
            .clone();

        if node.is_cache_2d {
            let slot = self
                .cache_slot_by_id
                .get(&node.id)
                .ok_or_else(|| format!("missing cache slot for {}", node.id.0))?;
            return Ok(format!("col.values[{}]", slot));
        }

        let expr = self.emit_node_expr(&node)?;
        if expr.len() > 80 || node.usage_count > 1 {
            let var = format!("v{}", self.var_counter);
            self.var_counter += 1;
            self.statements.push(format!("{} := {}", var, expr));
            self.var_names.insert(id.clone(), var.clone());
            Ok(var)
        } else {
            Ok(expr)
        }
    }

    fn emit_node_expr(&mut self, node: &DensityNode) -> Result<String, Box<dyn std::error::Error>> {
        Ok(match &node.def {
            DensityFunctionDef::Constant { argument } => fmt_f64(*argument),
            DensityFunctionDef::Add { .. } => format!(
                "({} + {})",
                self.emit_node(&node.dependencies[0])?,
                self.emit_node(&node.dependencies[1])?
            ),
            DensityFunctionDef::Mul { .. } => format!(
                "({} * {})",
                self.emit_node(&node.dependencies[0])?,
                self.emit_node(&node.dependencies[1])?
            ),
            DensityFunctionDef::Min { .. } => format!(
                "minFloat({}, {})",
                self.emit_node(&node.dependencies[0])?,
                self.emit_node(&node.dependencies[1])?
            ),
            DensityFunctionDef::Max { .. } => format!(
                "maxFloat({}, {})",
                self.emit_node(&node.dependencies[0])?,
                self.emit_node(&node.dependencies[1])?
            ),
            DensityFunctionDef::Clamp { min, max, .. } => format!(
                "clampFloat({}, {}, {})",
                self.emit_node(&node.dependencies[0])?,
                fmt_f64(*min),
                fmt_f64(*max)
            ),
            DensityFunctionDef::Abs { .. } => {
                format!("math.Abs({})", self.emit_node(&node.dependencies[0])?)
            }
            DensityFunctionDef::Square { .. } => {
                let v = self.emit_node(&node.dependencies[0])?;
                format!("({0} * {0})", v)
            }
            DensityFunctionDef::Cube { .. } => {
                let v = self.emit_node(&node.dependencies[0])?;
                format!("({0} * {0} * {0})", v)
            }
            DensityFunctionDef::Squeeze { .. } => {
                format!("squeeze({})", self.emit_node(&node.dependencies[0])?)
            }
            DensityFunctionDef::HalfNegative { .. } => {
                format!("halfNegative({})", self.emit_node(&node.dependencies[0])?)
            }
            DensityFunctionDef::QuarterNegative { .. } => {
                format!(
                    "quarterNegative({})",
                    self.emit_node(&node.dependencies[0])?
                )
            }
            DensityFunctionDef::Noise {
                noise,
                xz_scale,
                y_scale,
            } => format!(
                "noises.Sample({}, float64(ctx.BlockX)*{}, float64(ctx.BlockY)*{}, float64(ctx.BlockZ)*{})",
                noise_const_name(noise),
                fmt_f64(*xz_scale),
                fmt_f64(*y_scale),
                fmt_f64(*xz_scale)
            ),
            DensityFunctionDef::ShiftedNoise {
                noise,
                xz_scale,
                y_scale,
                ..
            } => format!(
                "noises.Sample({}, (float64(ctx.BlockX)+{})*{}, (float64(ctx.BlockY)+{})*{}, (float64(ctx.BlockZ)+{})*{})",
                noise_const_name(noise),
                self.emit_node(&node.dependencies[0])?,
                fmt_f64(*xz_scale),
                self.emit_node(&node.dependencies[1])?,
                fmt_f64(*y_scale),
                self.emit_node(&node.dependencies[2])?,
                fmt_f64(*xz_scale)
            ),
            DensityFunctionDef::YClampedGradient {
                from_y,
                to_y,
                from_value,
                to_value,
            } => format!(
                "yClampedGradient(ctx.BlockY, {}, {}, {}, {})",
                from_y,
                to_y,
                fmt_f64(*from_value),
                fmt_f64(*to_value)
            ),
            DensityFunctionDef::FlatCache { .. } => {
                let slot = self
                    .flat_slot_by_id
                    .get(&node.id)
                    .ok_or_else(|| format!("missing flat cache slot for {}", node.id.0))?;
                format!("flat.Lookup({}, ctx.BlockX, ctx.BlockZ)", slot)
            }
            DensityFunctionDef::Cache2D { .. } => {
                let slot = self
                    .cache_slot_by_id
                    .get(&node.id)
                    .ok_or_else(|| format!("missing cache slot for {}", node.id.0))?;
                format!("col.values[{}]", slot)
            }
            DensityFunctionDef::CacheOnce { .. }
            | DensityFunctionDef::Interpolated { .. }
            | DensityFunctionDef::BlendDensity { .. } => self.emit_node(&node.dependencies[0])?,
            DensityFunctionDef::BlendAlpha {} => "1.0".to_string(),
            DensityFunctionDef::BlendOffset {} => "0.0".to_string(),
            DensityFunctionDef::RangeChoice {
                min_inclusive,
                max_exclusive,
                ..
            } => format!(
                "func() float64 {{ inp := {}; if inp >= {} && inp < {} {{ return {} }}; return {} }}()",
                self.emit_node(&node.dependencies[0])?,
                fmt_f64(*min_inclusive),
                fmt_f64(*max_exclusive),
                self.emit_node(&node.dependencies[1])?,
                self.emit_node(&node.dependencies[2])?
            ),
            DensityFunctionDef::WeirdScaledSampler {
                noise,
                rarity_value_mapper,
                ..
            } => {
                let kind = if rarity_value_mapper == "type_1" {
                    "RarityType1"
                } else {
                    "RarityType2"
                };
                let input = self.emit_node(&node.dependencies[0])?;
                format!(
                    "func() float64 {{ rarity := rarityValue({}, {}); return rarity * math.Abs(noises.Sample({}, float64(ctx.BlockX)/rarity, float64(ctx.BlockY)/rarity, float64(ctx.BlockZ)/rarity)) }}()",
                    kind,
                    input,
                    noise_const_name(noise)
                )
            }
            DensityFunctionDef::ShiftA { argument } => format!(
                "noises.Sample({}, float64(ctx.BlockX), 0.0, float64(ctx.BlockZ)) * 4.0",
                noise_const_name(argument)
            ),
            DensityFunctionDef::ShiftB { argument } => format!(
                "noises.Sample({}, float64(ctx.BlockZ), float64(ctx.BlockX), 0.0) * 4.0",
                noise_const_name(argument)
            ),
            DensityFunctionDef::Shift { argument } => format!(
                "noises.Sample({}, float64(ctx.BlockX), 0.0, float64(ctx.BlockZ)) * 4.0",
                noise_const_name(argument)
            ),
            DensityFunctionDef::OldBlendedNoise {
                xz_scale,
                y_scale,
                xz_factor,
                y_factor,
                smear_scale_multiplier,
            } => format!(
                "noises.SampleBlendedNoise(float64(ctx.BlockX), float64(ctx.BlockY), float64(ctx.BlockZ), {}, {}, {}, {}, {})",
                fmt_f64(*xz_scale),
                fmt_f64(*y_scale),
                fmt_f64(*xz_factor),
                fmt_f64(*y_factor),
                fmt_f64(*smear_scale_multiplier)
            ),
            DensityFunctionDef::EndIslands {} => "0.0".to_string(),
            DensityFunctionDef::Invert { .. } => {
                format!("(-{})", self.emit_node(&node.dependencies[0])?)
            }
            DensityFunctionDef::Spline { .. } | DensityFunctionDef::FindTopSurface { .. } => {
                self.graph_eval_fallback(&node.id)
            }
        })
    }

    fn graph_eval_fallback(&self, id: &NodeId) -> String {
        let idx = self.index_by_id.get(id).copied().unwrap_or_default();
        format!("OverworldGraph.Eval({}, ctx, noises, flat, col, nil)", idx)
    }
}

fn emit_surface_rule_literal(rule: &RuleSource) -> Result<String, Box<dyn std::error::Error>> {
    match rule {
        RuleSource::Sequence { sequence } => {
            let children = sequence
                .iter()
                .map(emit_surface_rule_literal)
                .collect::<Result<Vec<_>, _>>()?;
            Ok(format!(
                "&surfaceRule{{kind: surfaceRuleSequence, sequence: []*surfaceRule{{{}}}}}",
                children.join(", ")
            ))
        }
        RuleSource::Condition { if_true, then_run } => Ok(format!(
            "&surfaceRule{{kind: surfaceRuleCondition, ifTrue: {}, thenRun: {}}}",
            emit_surface_condition_literal(if_true)?,
            emit_surface_rule_literal(then_run)?
        )),
        RuleSource::Block { result_state } => Ok(format!(
            "&surfaceRule{{kind: surfaceRuleBlock, block: {}}}",
            emit_surface_block_state_literal(result_state)?
        )),
        RuleSource::Bandlands {} => Ok("&surfaceRule{kind: surfaceRuleBandlands}".to_string()),
    }
}

fn emit_surface_condition_literal(
    condition: &ConditionSource,
) -> Result<String, Box<dyn std::error::Error>> {
    match condition {
        ConditionSource::Biome { biome_is } => {
            let biomes = biome_is
                .iter()
                .map(|name| emit_biome_const(name))
                .collect::<Result<Vec<_>, _>>()?;
            Ok(format!(
                "&surfaceCondition{{kind: surfaceConditionBiome, biomes: []Biome{{{}}}}}",
                biomes.join(", ")
            ))
        }
        ConditionSource::StoneDepth {
            offset,
            add_surface_depth,
            secondary_depth_range,
            surface_type,
        } => {
            let cave_surface = match surface_type.as_str() {
                "ceiling" => "surfaceCeiling",
                _ => "surfaceFloor",
            };
            Ok(format!(
                "&surfaceCondition{{kind: surfaceConditionStoneDepth, offset: {}, addSurfaceDepth: {}, secondaryDepthRange: {}, caveSurface: {}}}",
                offset, add_surface_depth, secondary_depth_range, cave_surface
            ))
        }
        ConditionSource::YAbove {
            anchor,
            surface_depth_multiplier,
            add_stone_depth,
        } => Ok(format!(
            "&surfaceCondition{{kind: surfaceConditionYAbove, anchor: {}, surfaceDepthMultiplier: {}, addStoneDepth: {}}}",
            emit_surface_anchor_literal(anchor),
            surface_depth_multiplier,
            add_stone_depth
        )),
        ConditionSource::Water {
            offset,
            surface_depth_multiplier,
            add_stone_depth,
        } => Ok(format!(
            "&surfaceCondition{{kind: surfaceConditionWater, offset: {}, surfaceDepthMultiplier: {}, addStoneDepth: {}}}",
            offset, surface_depth_multiplier, add_stone_depth
        )),
        ConditionSource::NoiseThreshold {
            noise,
            min_threshold,
            max_threshold,
        } => Ok(format!(
            "&surfaceCondition{{kind: surfaceConditionNoiseThreshold, noise: {}, minThreshold: {}, maxThreshold: {}}}",
            noise_const_name(noise),
            fmt_f64(*min_threshold),
            fmt_f64(*max_threshold)
        )),
        ConditionSource::VerticalGradient {
            random_name: _,
            true_at_and_below,
            false_at_and_above,
        } => Ok(format!(
            "&surfaceCondition{{kind: surfaceConditionVerticalGradient, trueAtAndBelow: {}, falseAtAndAbove: {}}}",
            emit_surface_anchor_literal(true_at_and_below),
            emit_surface_anchor_literal(false_at_and_above)
        )),
        ConditionSource::Steep {} => {
            Ok("&surfaceCondition{kind: surfaceConditionSteep}".to_string())
        }
        ConditionSource::Hole {} => Ok("&surfaceCondition{kind: surfaceConditionHole}".to_string()),
        ConditionSource::AbovePreliminarySurface {} => {
            Ok("&surfaceCondition{kind: surfaceConditionAbovePreliminarySurface}".to_string())
        }
        ConditionSource::Temperature {} => {
            Ok("&surfaceCondition{kind: surfaceConditionTemperature}".to_string())
        }
        ConditionSource::Not { invert } => Ok(format!(
            "&surfaceCondition{{kind: surfaceConditionNot, inner: {}}}",
            emit_surface_condition_literal(invert)?
        )),
    }
}

fn emit_surface_anchor_literal(anchor: &VerticalAnchor) -> String {
    match anchor {
        VerticalAnchor::AboveBottom { above_bottom } => format!(
            "surfaceVerticalAnchor{{kind: surfaceAnchorAboveBottom, value: {}}}",
            above_bottom
        ),
        VerticalAnchor::BelowTop { below_top } => format!(
            "surfaceVerticalAnchor{{kind: surfaceAnchorBelowTop, value: {}}}",
            below_top
        ),
        VerticalAnchor::Absolute { absolute } => format!(
            "surfaceVerticalAnchor{{kind: surfaceAnchorAbsolute, value: {}}}",
            absolute
        ),
    }
}

fn emit_surface_block_state_literal(
    state: &SurfaceBlockState,
) -> Result<String, Box<dyn std::error::Error>> {
    let properties = if let Some(props) = &state.properties {
        let mut entries: Vec<_> = props.iter().collect();
        entries.sort_by(|(a, _), (b, _)| a.cmp(b));
        let items = entries
            .into_iter()
            .map(|(key, value)| format!("{:?}: {:?}", key, value))
            .collect::<Vec<_>>()
            .join(", ");
        format!("map[string]string{{{}}}", items)
    } else {
        "nil".to_string()
    };

    Ok(format!(
        "surfaceBlockState{{name: {:?}, properties: {}}}",
        state.name, properties
    ))
}

fn emit_biome_const(name: &str) -> Result<String, Box<dyn std::error::Error>> {
    let trimmed = name.rsplit(':').next().unwrap_or(name);
    let biome = match trimmed {
        "windswept_gravelly_hills" => "BiomeGravellyMountains",
        "jungle_edge" => "BiomeSparseJungle",
        "old_growth_birch_forest" => "BiomeTallBirchForest",
        "giant_tree_taiga" => "BiomeOldGrowthPineTaiga",
        "giant_spruce_taiga" => "BiomeOldGrowthSpruceTaiga",
        "snowy_mountains" => "BiomeSnowyMountains",
        _ => return Ok(format!("Biome{}", go_pascal_name(name))),
    };
    Ok(biome.to_string())
}

fn join_isize_slice(values: &[isize]) -> String {
    values
        .iter()
        .map(|v| v.to_string())
        .collect::<Vec<_>>()
        .join(", ")
}

