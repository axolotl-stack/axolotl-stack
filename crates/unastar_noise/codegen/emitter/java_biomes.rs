//! Emits `java_biomes.rs`: the pinned Java version's biomes with their Bedrock ids and the
//! climate fields worldgen reads.

use proc_macro2::{Ident, Literal, Span, TokenStream};
use quote::quote;
use std::collections::{BTreeMap, HashMap};
use std::path::Path;

use crate::codegen::parser::biome::{BiomeJson, to_pascal_case};

/// Load `java_data/bedrock_biomes.json` (namespaced Java biome -> Bedrock id).
pub fn load_bedrock_ids(java_data: &Path) -> Result<BTreeMap<String, u32>, String> {
    let path = java_data.join("bedrock_biomes.json");
    let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))
}

pub fn emit(
    biomes: &HashMap<String, BiomeJson>,
    bedrock_ids: &BTreeMap<String, u32>,
) -> Result<TokenStream, String> {
    let mut names: Vec<&String> = biomes.keys().collect();
    names.sort();
    if names.len() > u8::MAX as usize {
        return Err("more Java biomes than fit JavaBiome's u8 discriminant".into());
    }

    let mut variants = Vec::new();
    let mut rows = Vec::new();
    for name in &names {
        let biome = &biomes[*name];
        let full = format!("minecraft:{name}");
        let bedrock = *bedrock_ids
            .get(&full)
            .ok_or_else(|| format!("java_data/bedrock_biomes.json has no Bedrock id for {full}"))?;
        let frozen = match biome.temperature_modifier.as_deref() {
            None | Some("none") => false,
            Some("frozen") => true,
            Some(other) => return Err(format!("{full}: unknown temperature_modifier {other}")),
        };
        let temperature = Literal::f32_suffixed(biome.temperature);
        let precipitation = biome.has_precipitation;
        let carvers = biome.carvers.clone().into_vec();
        variants.push(Ident::new(&to_pascal_case(name), Span::call_site()));
        rows.push(quote! {
            JavaBiomeData {
                name: #full,
                bedrock_id: #bedrock,
                temperature: #temperature,
                frozen: #frozen,
                has_precipitation: #precipitation,
                carvers: &[#(#carvers),*],
            }
        });
    }
    let count = names.len();
    let indices = (0..count).map(|i| Literal::u8_suffixed(i as u8));
    let all = variants.clone();

    Ok(quote! {
        //! Biomes of the pinned Java version (`worldgen_data/biome`), their Bedrock ids
        //! (`java_data/bedrock_biomes.json`) and climate fields.
        //! Generated by `codegen/emitter/java_biomes.rs`.

        /// A Java biome; the discriminant indexes [`JAVA_BIOMES`] (sorted by name).
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
        #[repr(u8)]
        pub enum JavaBiome {
            #(#variants = #indices),*
        }

        /// Data of one Java biome.
        #[derive(Debug, Clone, Copy, PartialEq)]
        pub struct JavaBiomeData {
            /// Namespaced name.
            pub name: &'static str,
            /// Bedrock numeric biome id.
            pub bedrock_id: u32,
            /// Base temperature.
            pub temperature: f32,
            /// `temperature_modifier: frozen`.
            pub frozen: bool,
            /// Whether it rains or snows.
            pub has_precipitation: bool,
            /// Configured carvers, in order.
            pub carvers: &'static [&'static str],
        }

        /// Every Java biome, indexed by [`JavaBiome`] discriminant.
        pub static JAVA_BIOMES: [JavaBiomeData; #count] = [#(#rows),*];

        impl JavaBiome {
            /// Number of biomes.
            pub const COUNT: usize = #count;

            /// Every biome, in discriminant order.
            pub const ALL: [JavaBiome; #count] = [#(JavaBiome::#all),*];

            /// Data of this biome.
            #[inline]
            pub fn data(self) -> &'static JavaBiomeData {
                &JAVA_BIOMES[self as usize]
            }

            /// Biome with a discriminant.
            #[inline]
            pub fn from_index(index: u16) -> Option<Self> {
                Self::ALL.get(index as usize).copied()
            }

            /// Biome with a namespaced name.
            pub fn from_name(name: &str) -> Option<Self> {
                JAVA_BIOMES
                    .binary_search_by(|data| data.name.cmp(name))
                    .ok()
                    .map(|i| Self::ALL[i])
            }
        }
    })
}
