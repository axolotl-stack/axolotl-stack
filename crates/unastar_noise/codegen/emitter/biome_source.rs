//! Emits a preset's multi-noise parameter R-tree as static arrays plus Java's
//! history-sensitive nearest-point search over it.

use proc_macro2::{Ident, Literal, Span, TokenStream};
use quote::quote;

use crate::codegen::data::biome_parameters::{BiomeParameters, DIMS, Node, Point, build};
use crate::codegen::parser::biome::to_pascal_case;

struct Flat {
    spaces: Vec<TokenStream>,
    first_child: Vec<u32>,
    child_count: Vec<u8>,
    biome: Vec<TokenStream>,
}

pub fn emit(preset: &str, params: &BiomeParameters) -> Result<TokenStream, String> {
    if params.biomes.is_empty() || params.points.is_empty() {
        return Err(format!("{preset} multi-noise biome parameter list is empty"));
    }
    let module_doc = format!(
        "Multi-noise biome source from `java_data/biome_parameters_{preset}.json`."
    );
    let biome_idents: Vec<Ident> = params
        .biomes
        .iter()
        .map(|name| {
            let short = name
                .strip_prefix("minecraft:")
                .ok_or_else(|| format!("biome {name} is not namespaced"))?;
            Ok(Ident::new(&to_pascal_case(short), Span::call_site()))
        })
        .collect::<Result<_, String>>()?;

    let leaves: Vec<Node> = params.points.iter().cloned().map(Node::Leaf).collect();
    let root = build(leaves);

    // Breadth-first flattening keeps each node's children contiguous.
    let mut flat = Flat {
        spaces: Vec::new(),
        first_child: Vec::new(),
        child_count: Vec::new(),
        biome: Vec::new(),
    };
    let mut queue = std::collections::VecDeque::from([root]);
    let mut next_index = 1u32;
    while let Some(node) = queue.pop_front() {
        let space = node.space();
        let rows = space.iter().map(|(min, max)| {
            let (min, max) = (Literal::i64_suffixed(*min), Literal::i64_suffixed(*max));
            quote! { [#min, #max] }
        });
        flat.spaces.push(quote! { [#(#rows),*] });
        match node {
            Node::Leaf(Point { biome, .. }) => {
                let ident = &biome_idents[biome];
                flat.first_child.push(0);
                flat.child_count.push(0);
                flat.biome.push(quote! { JavaBiome::#ident });
            }
            Node::Sub { children, .. } => {
                flat.first_child.push(next_index);
                flat.child_count.push(children.len() as u8);
                // Sub-trees carry a placeholder biome that the search never reads.
                let placeholder = &biome_idents[0];
                flat.biome.push(quote! { JavaBiome::#placeholder });
                next_index += children.len() as u32;
                queue.extend(children);
            }
        }
    }
    let count = flat.spaces.len();
    let Flat {
        spaces,
        first_child,
        child_count,
        biome,
    } = flat;
    let dims = DIMS;

    Ok(quote! {
        #![doc = #module_doc]
        //! Native parameter R-tree. Generated by `codegen/emitter/biome_source.rs`.

        use crate::java_biomes::JavaBiome;

        /// Parameters per point: temperature, humidity, continentalness, erosion, depth,
        /// weirdness, offset.
        pub const DIMS: usize = #dims;

        /// Bounding box (leaf: the point's ranges) of every node, `[min, max]` per parameter.
        static SPACE: [[[i64; 2]; #dims]; #count] = [#(#spaces),*];
        /// Index of a node's first child (children are contiguous).
        static FIRST_CHILD: [u32; #count] = [#(#first_child),*];
        /// Number of children; 0 marks a leaf.
        static CHILD_COUNT: [u8; #count] = [#(#child_count),*];
        /// Biome of each leaf.
        static BIOME: [JavaBiome; #count] = [#(#biome),*];

        /// Java's coordinate quantization of a climate value: `(long)((float) v * 10000.0F)`.
        #[inline]
        pub fn quantize(value: f64) -> i64 {
            ((value as f32) * 10000.0f32) as i64
        }

        #[inline]
        fn distance(node: usize, target: &[i64; #dims]) -> i64 {
            let mut sum = 0i64;
            for (span, &value) in SPACE[node].iter().zip(target) {
                let above = value - span[1];
                let below = span[0] - value;
                let d = if above > 0 { above } else { below.max(0) };
                sum += d * d;
            }
            sum
        }

        // Children are node indices into several parallel arrays.
        #[allow(clippy::needless_range_loop)]
        fn search(node: usize, target: &[i64; #dims], best: Option<usize>) -> Option<usize> {
            let mut best_distance = best.map_or(i64::MAX, |leaf| distance(leaf, target));
            let mut leaf = best;
            let first = FIRST_CHILD[node] as usize;
            for child in first..first + CHILD_COUNT[node] as usize {
                let d = distance(child, target);
                if best_distance > d {
                    let found = if CHILD_COUNT[child] == 0 {
                        Some(child)
                    } else {
                        search(child, target, leaf)
                    };
                    let Some(found) = found else { continue };
                    let e = if found == child { d } else { distance(found, target) };
                    if best_distance > e {
                        best_distance = e;
                        leaf = Some(found);
                    }
                }
            }
            leaf
        }

        /// Search history for one native parameter-list traversal.
        ///
        /// Equal-fitness points retain the previous leaf, including when the
        /// candidates name different biomes. A fresh history is a cold search;
        /// callers must not reset it between native section queries.
        #[derive(Clone, Copy, Debug, Default)]
        pub struct Search {
            previous: Option<usize>,
        }

        impl Search {
            pub const fn new() -> Self {
                Self { previous: None }
            }

            pub fn find(&mut self, target: &[i64; #dims]) -> JavaBiome {
                let leaf = if CHILD_COUNT[0] == 0 {
                    0
                } else {
                    search(0, target, self.previous).expect("biome R-tree has leaves")
                };
                self.previous = Some(leaf);
                BIOME[leaf]
            }
        }

        std::thread_local! {
            static SEARCH: std::cell::Cell<Search> =
                const { std::cell::Cell::new(Search::new()) };
        }

        /// Native lookup, retaining this parameter list's previous result on
        /// the calling thread just as Java's R-tree does. Query history can
        /// decide ties; this is deliberately not a pure function of `target`.
        pub fn find(target: &[i64; #dims]) -> JavaBiome {
            SEARCH.with(|slot| {
                let mut search = slot.get();
                let biome = search.find(target);
                slot.set(search);
                biome
            })
        }

        /// Quantized climate target from raw router values (offset dimension 0).
        #[inline]
        pub fn target(
            temperature: f64,
            humidity: f64,
            continentalness: f64,
            erosion: f64,
            depth: f64,
            weirdness: f64,
        ) -> [i64; #dims] {
            [
                quantize(temperature),
                quantize(humidity),
                quantize(continentalness),
                quantize(erosion),
                quantize(depth),
                quantize(weirdness),
                0,
            ]
        }
    })
}
