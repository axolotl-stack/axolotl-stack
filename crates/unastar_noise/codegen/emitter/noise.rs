//! Emits `noise_params` (noise parameters with their `fromHashOf` seeds) and
//! `random_hashes` (the other named random streams).

use proc_macro2::{Ident, Literal, Span, TokenStream};
use quote::quote;
use std::collections::HashMap;

use super::super::data::random_hash::hash_of;
use super::super::parser::noise::NoiseParams;

/// Lowest and highest octave index any octave noise may use (`octave_<n>` streams).
/// Positive indices exist (e.g. `badlands_pillar` spans -2..=1).
const OCTAVE_MIN: i32 = -16;
const OCTAVE_MAX: i32 = 16;

fn hash_tokens(name: &str) -> TokenStream {
    let (lo, hi) = hash_of(name);
    let lo = Literal::u64_suffixed(lo);
    let hi = Literal::u64_suffixed(hi);
    quote! { (#lo, #hi) }
}

fn legacy_hash(name: &str) -> i32 {
    name.encode_utf16().fold(0_i32, |hash, unit| {
        hash.wrapping_mul(31).wrapping_add(i32::from(unit))
    })
}

pub fn emit_noise_params(noises: &HashMap<String, NoiseParams>) -> Result<TokenStream, String> {
    let mut names: Vec<&String> = noises.keys().collect();
    names.sort();

    let variants: Vec<Ident> = names
        .iter()
        .map(|name| Ident::new(&noise_name_to_variant(name), Span::call_site()))
        .collect();
    let legacy_hashes = names.iter().map(|name| legacy_hash(name));
    let mut rows = Vec::new();
    for (name, variant) in names.iter().zip(&variants) {
        let params = &noises[*name];
        let last_octave = params.first_octave + params.amplitudes.len() as i32 - 1;
        if params.first_octave < OCTAVE_MIN || last_octave > OCTAVE_MAX {
            return Err(format!(
                "noise {name} uses octaves {}..={last_octave}, outside the generated octave_<n> range {OCTAVE_MIN}..={OCTAVE_MAX}",
                params.first_octave
            ));
        }
        let hash = hash_tokens(name);
        let first_octave = params.first_octave;
        let amplitudes = params.amplitudes.iter().map(|&a| Literal::f64_suffixed(a));
        rows.push(quote! {
            (NoiseRef::#variant, NoiseParamsData {
                name: #name,
                hash: #hash,
                first_octave: #first_octave,
                amplitudes: &[#(#amplitudes),*],
            })
        });
    }
    let count = names.len();
    Ok(quote! {
        //! Noise parameters from `worldgen_data/noise`, with the `fromHashOf` seed of each
        //! noise's name. Generated by `codegen/emitter/noise.rs`.

        /// A noise parameter set; the discriminant indexes [`NOISE_PARAMS`].
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        #[repr(usize)]
        pub enum NoiseRef {
            #(#variants),*
        }

        /// Parameters of one noise.
        #[derive(Debug, Clone)]
        pub struct NoiseParamsData {
            /// Namespaced noise name.
            pub name: &'static str,
            /// `fromHashOf(name)` seed: big-endian halves of `md5(name)`.
            pub hash: (u64, u64),
            pub first_octave: i32,
            pub amplitudes: &'static [f64],
        }

        impl NoiseRef {
            /// Number of noises.
            pub const COUNT: usize = #count;

            /// Parameters of this noise.
            #[inline]
            pub fn params(self) -> &'static NoiseParamsData {
                &NOISE_PARAMS[self as usize].1
            }

            /// Java string hash used by a legacy positional random factory.
            /// Generated here; runtime noise construction performs no string hashing.
            pub const fn legacy_name_hash(self) -> i32 {
                match self {
                    #(Self::#variants => #legacy_hashes),*
                }
            }
        }

        /// Every noise, in discriminant order.
        pub static NOISE_PARAMS: [(NoiseRef, NoiseParamsData); #count] = [#(#rows),*];
    })
}

/// Named random streams other than noises.
pub fn emit_random_hashes() -> TokenStream {
    let named = [
        (
            "TERRAIN",
            "minecraft:terrain",
            "Blended (legacy 3D) terrain noise.",
        ),
        ("AQUIFER", "minecraft:aquifer", "Aquifer positional random."),
        ("ORE", "minecraft:ore", "Ore vein positional random."),
        (
            "CLAY_BANDS",
            "minecraft:clay_bands",
            "Badlands terracotta bands.",
        ),
        (
            "WORLDGEN_REGION_RANDOM",
            "minecraft:worldgen_region_random",
            "Decoration region random (`WorldGenRegion.getRandom()`).",
        ),
    ];
    let consts = named.iter().map(|(ident, name, doc)| {
        let ident = Ident::new(ident, Span::call_site());
        let hash = hash_tokens(name);
        let doc = format!("`{name}`: {doc}");
        quote! {
            #[doc = #doc]
            pub const #ident: (u64, u64) = #hash;
        }
    });
    let octaves = (OCTAVE_MIN..=OCTAVE_MAX).map(|n| hash_tokens(&format!("octave_{n}")));
    let legacy_octaves = (OCTAVE_MIN..=OCTAVE_MAX).map(|n| legacy_hash(&format!("octave_{n}")));
    let octave_count = (OCTAVE_MAX - OCTAVE_MIN + 1) as usize;
    quote! {
        //! `fromHashOf` seeds of named random streams (big-endian halves of `md5(name)`).
        //! Generated by `codegen/emitter/noise.rs`.

        #(#consts)*

        /// Lowest octave index with a generated `octave_<n>` seed.
        pub const OCTAVE_MIN: i32 = #OCTAVE_MIN;

        /// `octave_<n>` seeds for `n` from `OCTAVE_MIN` upwards.
        pub static OCTAVES: [(u64, u64); #octave_count] = [#(#octaves),*];

        /// Java string hashes of the same octave names for legacy positional streams.
        pub static LEGACY_OCTAVES: [i32; #octave_count] = [#(#legacy_octaves),*];

        #[inline]
        pub fn legacy_octave(n: i32) -> i32 {
            LEGACY_OCTAVES[(n - OCTAVE_MIN) as usize]
        }

        /// Seed of the `octave_<n>` stream. Panics outside the generated range: the build
        /// checks every noise's octaves against it.
        #[inline]
        pub fn octave(n: i32) -> (u64, u64) {
            OCTAVES[(n - OCTAVE_MIN) as usize]
        }
    }
}

fn noise_name_to_variant(name: &str) -> String {
    let clean = name.strip_prefix("minecraft:").unwrap_or(name);
    // Convert snake_case to PascalCase
    clean
        .split('_')
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_uppercase().chain(chars).collect(),
            }
        })
        .collect()
}
