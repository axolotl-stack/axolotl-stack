//! Shared helpers for formatting and writing generated Rust modules.

use proc_macro2::TokenStream;
use quote::quote;
use std::fs::OpenOptions;
use std::io::Write;
use std::path::Path;
use std::sync::atomic::{AtomicU64, Ordering};

const GENERATED_HEADER: &str = "// Generated by valentine_gen. Do not edit.\n\n";

fn format_tokens(
    tokens: TokenStream,
    debug_name: Option<&str>,
) -> Result<String, Box<dyn std::error::Error>> {
    let syntax_tree = syn::parse2(tokens.clone()).map_err(|err| {
        if let Some(path) = debug_name {
            let _ = std::fs::write(path, tokens.to_string());
        }
        format!("Failed to parse generated code: {err}")
    })?;

    Ok(prettyplease::unparse(&syntax_tree))
}

pub fn write_rust_file(
    path: &Path,
    tokens: TokenStream,
    debug_name: Option<&str>,
) -> Result<(), Box<dyn std::error::Error>> {
    let formatted = format_tokens(tokens, debug_name)?;
    static NEXT_TEMP_ID: AtomicU64 = AtomicU64::new(0);
    let (temp_path, mut file) = loop {
        let mut name = path
            .file_name()
            .ok_or("Rust output path has no file name")?
            .to_os_string();
        name.push(format!(
            ".{}.{}.tmp",
            std::process::id(),
            NEXT_TEMP_ID.fetch_add(1, Ordering::Relaxed)
        ));
        let temp_path = path.with_file_name(name);
        match OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&temp_path)
        {
            Ok(file) => break (temp_path, file),
            Err(err) if err.kind() == std::io::ErrorKind::AlreadyExists => continue,
            Err(err) => return Err(err.into()),
        }
    };
    // Stage beside the destination so rename remains an atomic replacement.
    let result = (|| -> std::io::Result<()> {
        file.write_all(GENERATED_HEADER.as_bytes())?;
        file.write_all(formatted.as_bytes())?;
        file.flush()
    })();
    drop(file);
    let result = result.and_then(|()| std::fs::rename(&temp_path, path));
    if result.is_err() {
        let _ = std::fs::remove_file(&temp_path);
    }
    result.map_err(Into::into)
}

pub fn generated_module_tokens(
    doc: Option<&str>,
    imports: TokenStream,
    items: &[TokenStream],
) -> TokenStream {
    let doc_tokens = doc.map(|text| quote! { #![doc = #text] });

    quote! {
        #doc_tokens
        #![allow(non_camel_case_types)]
        #![allow(non_snake_case)]
        #![allow(dead_code)]
        #![allow(unused_parens)]
        // Codec signatures are uniform across packets, so a packet whose
        // decode needs no arguments still takes them.
        #![allow(unused_variables)]
        #![allow(clippy::all)]
        #imports

        #(#items)*
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn invalid_tokens_preserve_existing_file() {
        let path = std::env::temp_dir().join(format!(
            "valentine-emitter-invalid-{}.rs",
            std::process::id()
        ));
        let original = b"// Existing generated output\npub struct Existing;\n";
        std::fs::write(&path, original).unwrap();

        let result = write_rust_file(&path, quote! { pub struct }, None);
        let actual = std::fs::read(&path).unwrap();
        std::fs::remove_file(&path).unwrap();

        assert!(result.is_err());
        assert_eq!(actual, original);
    }

    #[test]
    fn valid_tokens_replace_existing_file() {
        let path =
            std::env::temp_dir().join(format!("valentine-emitter-valid-{}.rs", std::process::id()));
        std::fs::write(&path, "old output that must be replaced completely").unwrap();

        write_rust_file(&path, quote! { pub struct Replacement; }, None).unwrap();
        let actual = std::fs::read_to_string(&path).unwrap();
        std::fs::remove_file(&path).unwrap();

        assert_eq!(
            actual,
            format!("{GENERATED_HEADER}pub struct Replacement;\n")
        );
    }
}
