//! `docs/parity/PARITY.md`: counts per domain and family, then gap lists.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::catalog::{DomainRows, Row};
use crate::status::{Status, StatusFile};

/// Ids listed per gap line before the rest are summarised as "and N more";
/// the status file has them all.
const LIST_IDS_UP_TO: usize = 12;
/// Gap groups (rows sharing one `gaps` text) shown per family.
const GAP_GROUPS_UP_TO: usize = 5;
/// Rows in the "most-needed sub-rows" rollup.
const FACET_ROLLUP: usize = 30;

#[derive(Default, Clone, Copy)]
struct Counts {
    by_status: [usize; 5],
}

impl Counts {
    fn add(&mut self, status: Status) {
        self.by_status[status as usize] += 1;
    }
    fn get(&self, status: Status) -> usize {
        self.by_status[status as usize]
    }
    fn total(&self) -> usize {
        self.by_status.iter().sum()
    }
    fn complete(&self) -> usize {
        self.get(Status::Done) + self.get(Status::Verified)
    }
    /// Done + verified over rows that apply.
    fn percent(&self) -> String {
        let applicable = self.total() - self.get(Status::NotApplicable);
        if applicable == 0 {
            return "n/a".to_owned();
        }
        format!("{:.1}%", self.complete() as f64 * 100.0 / applicable as f64)
    }
    fn cells(&self) -> String {
        format!(
            "{} | {} | {} | {} | {} | {} | {}",
            self.total(),
            self.get(Status::Missing),
            self.get(Status::Partial),
            self.get(Status::Done),
            self.get(Status::Verified),
            self.get(Status::NotApplicable),
            self.percent()
        )
    }
}

const COUNT_HEADER: &str = "Rows | Missing | Partial | Done | Verified | N/A | Done+verified";
const COUNT_RULE: &str = "---:|---:|---:|---:|---:|---:|---:";

pub fn render(domains: &[(DomainRows, StatusFile)]) -> String {
    let mut out = String::new();
    out.push_str(
        "# Vanilla parity\n\n\
         Generated by `cargo run -p parity -- generate` from vanilla data and the status files \
         in this directory; do not edit by hand. Target: Bedrock Dedicated Server 1.26.51 \
         (protocol 2193); Java world-generation rows target Java Edition 1.21.11. Row meanings, \
         the status schema and the update rule are in [README.md](README.md).\n\n\
         *Done+verified* is (done + verified) / (rows - N/A). `verified` means a test compares \
         against committed native evidence; `done` means a test exists.\n\n",
    );

    out.push_str("## Summary\n\n");
    let _ = writeln!(out, "| Domain | {COUNT_HEADER} |");
    let _ = writeln!(out, "|---|{COUNT_RULE}|");
    for (rows, entries) in domains {
        let top = counts(rows.rows.iter().filter(|r| r.parent.is_none()), entries);
        let _ = writeln!(
            out,
            "| [{}](#{}) | {} |",
            rows.domain.title(),
            anchor(rows.domain.title()),
            top.cells()
        );
        if rows.rows.iter().any(|r| r.parent.is_some()) {
            let sub = counts(rows.rows.iter().filter(|r| r.parent.is_some()), entries);
            let _ = writeln!(
                out,
                "| {} sub-rows | {} |",
                rows.domain.title(),
                sub.cells()
            );
        }
    }
    out.push('\n');

    for (rows, entries) in domains {
        render_domain(&mut out, rows, entries);
    }
    out
}

fn render_domain(out: &mut String, rows: &DomainRows, entries: &StatusFile) {
    let domain = rows.domain;
    let _ = write!(
        out,
        "## {}\n\n{} Status file: [{}.toml]({}.toml).\n\n",
        domain.title(),
        domain.row_meaning(),
        domain.name(),
        domain.name()
    );

    let mut families: BTreeMap<&str, Vec<&Row>> = BTreeMap::new();
    for row in &rows.rows {
        families.entry(&row.family).or_default().push(row);
    }
    let has_sub_rows = rows.rows.iter().any(|r| r.parent.is_some());
    let _ = writeln!(out, "| Family | {COUNT_HEADER} |");
    let _ = writeln!(out, "|---|{COUNT_RULE}|");
    for (family, members) in &families {
        let top = counts(
            members.iter().copied().filter(|r| r.parent.is_none()),
            entries,
        );
        let _ = writeln!(out, "| {family} | {} |", top.cells());
    }
    out.push('\n');
    if has_sub_rows {
        render_facets(out, rows, entries);
    }

    let _ = writeln!(out, "### {} gaps\n", domain.title());
    if has_sub_rows {
        out.push_str(
            "Top-level rows only; sub-row gaps are in the status file and rolled up by facet \
             above.\n\n",
        );
    }
    let mut any = false;
    for (family, members) in &families {
        let top = || members.iter().copied().filter(|r| r.parent.is_none());
        // Partial rows grouped by identical gap text, largest group first.
        let mut partial: Vec<(&str, Vec<&Row>)> = Vec::new();
        for row in top().filter(|r| entries[&r.id].status == Status::Partial) {
            let gaps = entries[&row.id].gaps.as_str();
            match partial.iter_mut().find(|(text, _)| *text == gaps) {
                Some((_, rows)) => rows.push(row),
                None => partial.push((gaps, vec![row])),
            }
        }
        partial.sort_by_key(|(_, rows)| std::cmp::Reverse(rows.len()));
        let missing: Vec<&Row> = top()
            .filter(|r| entries[&r.id].status == Status::Missing)
            .collect();
        if partial.is_empty() && missing.is_empty() {
            continue;
        }
        any = true;
        let _ = writeln!(out, "**{family}**\n");
        for (gaps, rows) in partial.iter().take(GAP_GROUPS_UP_TO) {
            let _ = writeln!(out, "- {}: {gaps}", id_list(rows, LIST_IDS_UP_TO));
        }
        let other: usize = partial
            .iter()
            .skip(GAP_GROUPS_UP_TO)
            .map(|(_, rows)| rows.len())
            .sum();
        if other > 0 {
            let _ = writeln!(
                out,
                "- {other} more partial rows with other gaps (see [{0}.toml]({0}.toml))",
                domain.name()
            );
        }
        if !missing.is_empty() {
            let _ = writeln!(out, "- missing: {}", id_list(&missing, LIST_IDS_UP_TO));
        }
        out.push('\n');
    }
    if !any {
        out.push_str("None.\n\n");
    }
}

/// `` `a`, `b` `` or `` `a`, `b` and 12 more ``.
fn id_list(rows: &[&Row], up_to: usize) -> String {
    let shown: Vec<String> = rows
        .iter()
        .take(up_to)
        .map(|r| format!("`{}`", r.id))
        .collect();
    let mut list = shown.join(", ");
    if rows.len() > up_to {
        let _ = write!(list, " and {} more", rows.len() - up_to);
    }
    list
}

/// Sub-rows rolled up by facet (entity component, item behaviour), most
/// incomplete first: what to build next to unblock the most rows.
fn render_facets(out: &mut String, rows: &DomainRows, entries: &StatusFile) {
    let mut facets: BTreeMap<&str, Counts> = BTreeMap::new();
    for row in &rows.rows {
        if let Some(facet) = row.facet() {
            facets
                .entry(facet)
                .or_default()
                .add(entries[&row.id].status);
        }
    }
    let mut ranked: Vec<(&str, Counts)> = facets.into_iter().collect();
    ranked.sort_by(|(a_name, a), (b_name, b)| {
        let open = |c: &Counts| c.total() - c.complete() - c.get(Status::NotApplicable);
        open(b).cmp(&open(a)).then_with(|| a_name.cmp(b_name))
    });
    let shown = ranked.len().min(FACET_ROLLUP);
    let _ = writeln!(
        out,
        "Sub-rows by facet, most incomplete first ({shown} of {}):\n",
        ranked.len()
    );
    let _ = writeln!(out, "| Facet | {COUNT_HEADER} |");
    let _ = writeln!(out, "|---|{COUNT_RULE}|");
    for (facet, counts) in ranked.iter().take(shown) {
        let _ = writeln!(out, "| {facet} | {} |", counts.cells());
    }
    out.push('\n');
}

fn counts<'a>(rows: impl Iterator<Item = &'a Row>, entries: &StatusFile) -> Counts {
    let mut counts = Counts::default();
    for row in rows {
        counts.add(entries[&row.id].status);
    }
    counts
}

/// GitHub heading anchor.
fn anchor(title: &str) -> String {
    title
        .to_ascii_lowercase()
        .chars()
        .filter_map(|c| match c {
            ' ' => Some('-'),
            c if c.is_alphanumeric() || c == '-' => Some(c),
            _ => None,
        })
        .collect()
}
