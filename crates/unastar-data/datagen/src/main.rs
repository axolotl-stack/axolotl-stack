use clap::Parser;
use std::path::PathBuf;
use tracing::info;

mod bds;
mod blocks;
mod manifest;
mod nbt;
mod pmmp;
mod shapes;

#[derive(Parser, Debug)]
#[command(name = "unastar-data-gen")]
#[command(about = "Merge Bedrock data sources into clean KDL artifacts")]
struct Args {
    /// Path to vanilla behavior pack entities directory
    #[arg(long, default_value = "../data/vanilla_bp/behavior_pack/entities")]
    vanilla: PathBuf,

    /// Path to vanilla behavior pack biomes directory
    #[arg(long, default_value = "../data/vanilla_bp/behavior_pack/biomes")]
    vanilla_biomes: PathBuf,

    /// Path to vanilla behavior pack loot tables directory
    #[arg(long, default_value = "../data/vanilla_bp/behavior_pack/loot_tables")]
    vanilla_loot: PathBuf,

    /// Path to overrides directory
    #[arg(long, default_value = "../data/overrides")]
    overrides: PathBuf,

    /// Output directory for KDL artifacts
    #[arg(short, long, default_value = "../output")]
    output: PathBuf,

    /// List available entities and exit
    #[arg(long)]
    list: bool,

    /// Only refresh output/manifest.kdl from existing output artifacts
    #[arg(long, conflicts_with_all = ["pmmp_only", "blocks_only", "biomes_only", "bds_only", "loot_only"])]
    manifest_only: bool,

    /// Only refresh PMMP-derived output artifacts and the manifest
    #[arg(long, conflicts_with_all = ["manifest_only", "blocks_only", "biomes_only", "bds_only", "loot_only"])]
    pmmp_only: bool,

    /// Only refresh native block artifacts and the manifest
    #[arg(long, conflicts_with_all = ["manifest_only", "pmmp_only", "biomes_only", "bds_only", "loot_only"])]
    blocks_only: bool,

    /// Refresh the manifest for biomes generated by the unastar-data build script
    #[arg(long, conflicts_with_all = ["manifest_only", "pmmp_only", "blocks_only", "bds_only", "loot_only"])]
    biomes_only: bool,

    /// Only refresh BDS extractor-derived packet/runtime artifacts and the manifest
    #[arg(long, conflicts_with_all = ["manifest_only", "pmmp_only", "blocks_only", "biomes_only", "loot_only"])]
    bds_only: bool,

    /// Only refresh loot tables (vanilla BP + block overrides) and the manifest
    #[arg(long, conflicts_with_all = ["manifest_only", "pmmp_only", "blocks_only", "biomes_only", "bds_only"])]
    loot_only: bool,

    /// Only refresh per-state block shapes (protocolgen catalog) and the manifest
    #[arg(long, conflicts_with_all = ["manifest_only", "pmmp_only", "blocks_only", "biomes_only", "bds_only", "loot_only"])]
    shapes_only: bool,

    /// Path to a validated bds-extractor JSON capture for packet/runtime facts
    #[arg(long)]
    bds_extraction: Option<PathBuf>,

    /// Tracing filter
    #[arg(long, default_value = "info")]
    log: String,
}

fn main() -> miette::Result<()> {
    let args = Args::parse();

    tracing_subscriber::fmt().with_env_filter(&args.log).init();

    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));

    info!("unastar-data-gen starting...");
    info!("Vanilla BP: {}", manifest_dir.join(&args.vanilla).display());
    info!(
        "Vanilla biomes: {}",
        manifest_dir.join(&args.vanilla_biomes).display()
    );
    info!(
        "Overrides: {}",
        manifest_dir.join(&args.overrides).display()
    );
    info!("Output: {}", manifest_dir.join(&args.output).display());

    let vanilla_path = manifest_dir.join(&args.vanilla);
    let vanilla_biomes_path = manifest_dir.join(&args.vanilla_biomes);
    let vanilla_loot_path = manifest_dir.join(&args.vanilla_loot);
    let overrides_path = manifest_dir.join(&args.overrides);
    let block_loot_path = overrides_path.join("loot_tables/blocks.json");
    let output_path = manifest_dir.join(&args.output);
    let upstream_path = manifest_dir.join("../data/upstream");
    let pmmp_path = upstream_path.join("pmmp");
    let native_path =
        manifest_dir.join("../../valentine_gen/protocolgen/data/source/inputs/1.26.51/native");
    let protocolgen_data_path = manifest_dir.join("../../valentine_gen/protocolgen/generated/data");
    let bds_extraction_path = args
        .bds_extraction
        .as_ref()
        .map(|path| resolve_cli_path(&manifest_dir, path));
    let write_manifest = |bds_extraction_path: Option<&std::path::Path>| {
        manifest::write_manifest(
            &output_path,
            &manifest::ManifestInputs {
                vanilla_path: &vanilla_path,
                vanilla_biomes_path: &vanilla_biomes_path,
                vanilla_loot_path: &vanilla_loot_path,
                block_loot_path: &block_loot_path,
                overrides_path: &overrides_path,
                upstream_path: &upstream_path,
                pmmp_path: &pmmp_path,
                native_path: &native_path,
                bds_extraction_path,
            },
        )
    };

    if args.manifest_only {
        write_manifest(bds_extraction_path.as_deref())?;
        return Ok(());
    }

    if args.pmmp_only {
        pmmp::write_pmmp_artifacts(&native_path, &pmmp_path, &output_path)?;
        write_manifest(None)?;
        return Ok(());
    }

    if args.blocks_only {
        blocks::write_blocks_kdl(&native_path, &output_path)?;
        write_manifest(None)?;
        return Ok(());
    }

    if args.shapes_only {
        shapes::write_shapes(&protocolgen_data_path, &native_path, &output_path)?;
        write_manifest(None)?;
        return Ok(());
    }

    if args.biomes_only {
        write_manifest(None)?;
        return Ok(());
    }

    if args.loot_only {
        write_manifest(None)?;
        return Ok(());
    }

    if args.bds_only {
        let Some(bds_extraction_path) = bds_extraction_path.as_ref() else {
            return Err(miette::miette!(
                "--bds-only requires --bds-extraction <bds-extractor-json>"
            ));
        };
        bds::write_bds_artifacts(bds_extraction_path, &output_path)?;
        write_manifest(Some(bds_extraction_path))?;
        return Ok(());
    }

    if args.list {
        for actor in unastar_data::actor_definitions::vanilla() {
            println!("{}", actor.identifier());
        }
        return Ok(());
    }

    // Actor and biome artefacts are generated by unastar-data/build.rs into
    // OUT_DIR. They are never emitted into the source tree (D13).
    info!("Writing open-data KDL output...");
    blocks::write_blocks_kdl(&native_path, &output_path)?;
    shapes::write_shapes(&protocolgen_data_path, &native_path, &output_path)?;
    pmmp::write_pmmp_artifacts(&native_path, &pmmp_path, &output_path)?;
    if let Some(bds_extraction_path) = bds_extraction_path.as_ref() {
        bds::write_bds_artifacts(bds_extraction_path, &output_path)?;
    }
    write_manifest(bds_extraction_path.as_deref())?;

    info!("Done!");
    Ok(())
}

fn resolve_cli_path(manifest_dir: &std::path::Path, path: &std::path::Path) -> PathBuf {
    if path.is_absolute() {
        return path.to_path_buf();
    }

    let cwd_path = std::env::current_dir()
        .map(|cwd| cwd.join(path))
        .unwrap_or_else(|_| path.to_path_buf());
    if cwd_path.exists() {
        cwd_path
    } else {
        manifest_dir.join(path)
    }
}
