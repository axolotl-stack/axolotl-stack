//! Emit merged entity data as idiomatic KDL.
//!
//! This module produces clean, human-readable KDL that leverages KDL's strengths:
//! - Arguments for primary values (e.g., `health 20` not `health value=20`)
//! - Repeated nodes instead of `item0`, `item1` (e.g., multiple `filter` nodes)
//! - Semantic node names (e.g., `filter`, `event`, `trigger`)
//! - Properties for named configuration options

use crate::ir::*;
use kdl::{KdlDocument, KdlEntry, KdlNode, KdlValue};
use std::collections::HashMap;
use std::path::Path;
use tracing::info;

pub fn write_entities_kdl(
    entities: &HashMap<String, EntityDef>,
    output_dir: &Path,
) -> miette::Result<()> {
    let mut doc = KdlDocument::new();

    // Sort entities by name for deterministic output
    let mut sorted_names: Vec<_> = entities.keys().collect();
    sorted_names.sort();

    for name in sorted_names {
        let entity = &entities[name];
        let node = entity_to_kdl_node(entity);
        doc.nodes_mut().push(node);
    }

    // Format the document for readability
    doc.autoformat();

    // Write to file with header comment
    let output_path = output_dir.join("entities.kdl");
    std::fs::create_dir_all(output_dir)
        .map_err(|e| miette::miette!("Failed to create output dir: {}", e))?;

    let header = format!(
        "// AUTO-GENERATED by unastar-data-gen\n\
         // Do not edit manually - changes will be overwritten\n\
         // Entity count: {}\n\n",
        entities.len()
    );
    let content = format!("{}{}", header, doc);

    std::fs::write(&output_path, content)
        .map_err(|e| miette::miette!("Failed to write KDL: {}", e))?;

    info!(
        "Wrote {} entities to {}",
        entities.len(),
        output_path.display()
    );

    Ok(())
}

fn entity_to_kdl_node(entity: &EntityDef) -> KdlNode {
    let mut node = KdlNode::new("entity");
    node.push(KdlEntry::new(KdlValue::String(entity.identifier.clone())));

    let mut children = KdlDocument::new();

    // Basic info
    if let Some(spawn_cat) = &entity.spawn_category {
        let mut n = KdlNode::new("spawn_category");
        n.push(KdlEntry::new(KdlValue::String(spawn_cat.clone())));
        children.nodes_mut().push(n);
    }

    let mut spawnable = KdlNode::new("is_spawnable");
    spawnable.push(KdlEntry::new(KdlValue::Bool(entity.is_spawnable)));
    children.nodes_mut().push(spawnable);

    let mut summonable = KdlNode::new("is_summonable");
    summonable.push(KdlEntry::new(KdlValue::Bool(entity.is_summonable)));
    children.nodes_mut().push(summonable);

    if let Some(id) = entity.runtime_id {
        let mut n = KdlNode::new("runtime_id");
        n.push(KdlEntry::new(KdlValue::Integer(id as i128)));
        children.nodes_mut().push(n);
    }

    // Properties
    if !entity.properties.is_empty() {
        children.nodes_mut().push(properties_to_kdl(&entity.properties));
    }

    // Components
    if !entity.components.is_empty() {
        children.nodes_mut().push(components_to_kdl(&entity.components));
    }

    // Component groups
    if !entity.component_groups.is_empty() {
        children.nodes_mut().push(component_groups_to_kdl(&entity.component_groups));
    }

    // Events
    if !entity.events.is_empty() {
        children.nodes_mut().push(events_to_kdl(&entity.events));
    }

    node.set_children(children);
    node
}

fn properties_to_kdl(properties: &HashMap<String, PropertyDef>) -> KdlNode {
    let mut node = KdlNode::new("properties");
    let mut children = KdlDocument::new();

    let mut sorted: Vec<_> = properties.iter().collect();
    sorted.sort_by_key(|(k, _)| *k);

    for (name, prop) in sorted {
        let clean_name = name.strip_prefix("minecraft:").unwrap_or(name);
        let mut prop_node = KdlNode::new(clean_name);

        match &prop.prop_type {
            PropertyType::Enum { values } => {
                prop_node.push(KdlEntry::new_prop("type", KdlValue::String("enum".into())));
                prop_node.push(KdlEntry::new_prop("client_sync", KdlValue::Bool(prop.client_sync)));

                let mut prop_children = KdlDocument::new();

                // Use repeated "value" nodes instead of a single "values" node with args
                for v in values {
                    let mut value_node = KdlNode::new("value");
                    value_node.push(KdlEntry::new(KdlValue::String(v.clone())));
                    prop_children.nodes_mut().push(value_node);
                }

                let mut default_node = KdlNode::new("default");
                default_node.push(KdlEntry::new(KdlValue::String(prop.default.clone())));
                prop_children.nodes_mut().push(default_node);

                prop_node.set_children(prop_children);
            }
            PropertyType::Int { range } => {
                prop_node.push(KdlEntry::new_prop("type", KdlValue::String("int".into())));
                prop_node.push(KdlEntry::new_prop("min", KdlValue::Integer(range.0 as i128)));
                prop_node.push(KdlEntry::new_prop("max", KdlValue::Integer(range.1 as i128)));
                prop_node.push(KdlEntry::new_prop("default", KdlValue::String(prop.default.clone())));
                prop_node.push(KdlEntry::new_prop("client_sync", KdlValue::Bool(prop.client_sync)));
            }
            PropertyType::Float { range } => {
                prop_node.push(KdlEntry::new_prop("type", KdlValue::String("float".into())));
                prop_node.push(KdlEntry::new_prop("min", KdlValue::Float(range.0 as f64)));
                prop_node.push(KdlEntry::new_prop("max", KdlValue::Float(range.1 as f64)));
                prop_node.push(KdlEntry::new_prop("default", KdlValue::String(prop.default.clone())));
                prop_node.push(KdlEntry::new_prop("client_sync", KdlValue::Bool(prop.client_sync)));
            }
            PropertyType::Bool => {
                prop_node.push(KdlEntry::new_prop("type", KdlValue::String("bool".into())));
                prop_node.push(KdlEntry::new_prop("default", KdlValue::Bool(prop.default == "true")));
                prop_node.push(KdlEntry::new_prop("client_sync", KdlValue::Bool(prop.client_sync)));
            }
        }

        children.nodes_mut().push(prop_node);
    }

    node.set_children(children);
    node
}

fn components_to_kdl(components: &HashMap<String, ComponentValue>) -> KdlNode {
    let mut node = KdlNode::new("components");
    let mut children = KdlDocument::new();

    let mut sorted: Vec<_> = components.iter().collect();
    sorted.sort_by_key(|(k, _)| *k);

    for (name, value) in sorted {
        children.nodes_mut().push(component_value_to_kdl(name, value));
    }

    node.set_children(children);
    node
}

fn component_value_to_kdl(name: &str, value: &ComponentValue) -> KdlNode {
    let clean_name = name.strip_prefix("minecraft:").unwrap_or(name);
    let mut node = KdlNode::new(clean_name);

    match value {
        ComponentValue::Marker => {
            // Empty node - marker component
        }
        ComponentValue::Data(json) => {
            add_json_to_component(&mut node, json, clean_name);
        }
    }

    node
}

/// Smart JSON to KDL conversion for components
/// Handles special patterns like:
/// - Single "value" field -> argument (health 20)
/// - Arrays -> repeated semantic nodes
/// - Filters -> proper filter nodes
fn add_json_to_component(node: &mut KdlNode, json: &serde_json::Value, component_name: &str) {
    match json {
        serde_json::Value::Object(obj) => {
            // Check for single "value" field pattern -> use as argument
            if obj.len() == 1 {
                if let Some(val) = obj.get("value") {
                    if is_simple_value(val) {
                        node.push(KdlEntry::new(json_to_kdl_value(val)));
                        return;
                    }
                }
            }

            // Check if all values are simple enough to inline as properties
            let all_simple = obj.values().all(is_simple_value);
            let small_enough = obj.len() <= 6;

            if all_simple && small_enough {
                // Inline as properties, but extract "value" as first argument if present
                let mut sorted: Vec<_> = obj.iter().collect();
                sorted.sort_by_key(|(k, _)| *k);

                // Put "value" first as an argument
                if let Some(val) = obj.get("value") {
                    node.push(KdlEntry::new(json_to_kdl_value(val)));
                }

                for (k, v) in sorted {
                    if k == "value" {
                        continue; // Already added as argument
                    }
                    node.push(KdlEntry::new_prop(k.as_str(), json_to_kdl_value(v)));
                }
            } else {
                // Complex object - use children with semantic handling
                let children = json_to_kdl_children_semantic(json, component_name);
                if !children.nodes().is_empty() {
                    node.set_children(children);
                }
            }
        }
        _ => {
            // Single value - use as argument
            node.push(KdlEntry::new(json_to_kdl_value(json)));
        }
    }
}

fn component_groups_to_kdl(groups: &HashMap<String, HashMap<String, ComponentValue>>) -> KdlNode {
    let mut node = KdlNode::new("component_groups");
    let mut children = KdlDocument::new();

    let mut sorted: Vec<_> = groups.iter().collect();
    sorted.sort_by_key(|(k, _)| *k);

    for (name, components) in sorted {
        let clean_name = name.strip_prefix("minecraft:").unwrap_or(name);
        let mut group_node = KdlNode::new("group");
        group_node.push(KdlEntry::new(KdlValue::String(clean_name.to_string())));

        let mut group_children = KdlDocument::new();

        let mut sorted_comps: Vec<_> = components.iter().collect();
        sorted_comps.sort_by_key(|(k, _)| *k);

        for (comp_name, comp_value) in sorted_comps {
            group_children.nodes_mut().push(component_value_to_kdl(comp_name, comp_value));
        }

        group_node.set_children(group_children);
        children.nodes_mut().push(group_node);
    }

    node.set_children(children);
    node
}

fn events_to_kdl(events: &HashMap<String, EventDef>) -> KdlNode {
    let mut node = KdlNode::new("events");
    let mut children = KdlDocument::new();

    let mut sorted: Vec<_> = events.iter().collect();
    sorted.sort_by_key(|(k, _)| *k);

    for (name, event) in sorted {
        let clean_name = name.strip_prefix("minecraft:").unwrap_or(name);
        let mut event_node = KdlNode::new("event");
        event_node.push(KdlEntry::new(KdlValue::String(clean_name.to_string())));

        let mut event_children = KdlDocument::new();

        // Use repeated "add" nodes for each group
        for g in &event.add_groups {
            let mut add_node = KdlNode::new("add");
            add_node.push(KdlEntry::new(KdlValue::String(g.clone())));
            event_children.nodes_mut().push(add_node);
        }

        // Use repeated "remove" nodes for each group
        for g in &event.remove_groups {
            let mut remove_node = KdlNode::new("remove");
            remove_node.push(KdlEntry::new(KdlValue::String(g.clone())));
            event_children.nodes_mut().push(remove_node);
        }

        if let Some(trigger) = &event.trigger {
            let mut trigger_node = KdlNode::new("trigger");
            trigger_node.push(KdlEntry::new(KdlValue::String(trigger.clone())));
            event_children.nodes_mut().push(trigger_node);
        }

        if !event.randomize.is_empty() {
            let mut randomize_node = KdlNode::new("randomize");
            let mut rand_children = KdlDocument::new();

            for entry in &event.randomize {
                let mut option_node = KdlNode::new("option");
                option_node.push(KdlEntry::new_prop("weight", KdlValue::Integer(entry.weight as i128)));
                if let Some(trigger) = &entry.trigger {
                    option_node.push(KdlEntry::new_prop("trigger", KdlValue::String(trigger.clone())));
                }
                rand_children.nodes_mut().push(option_node);
            }

            randomize_node.set_children(rand_children);
            event_children.nodes_mut().push(randomize_node);
        }

        if !event_children.nodes().is_empty() {
            event_node.set_children(event_children);
        }

        children.nodes_mut().push(event_node);
    }

    node.set_children(children);
    node
}

fn is_simple_value(v: &serde_json::Value) -> bool {
    matches!(
        v,
        serde_json::Value::Null
            | serde_json::Value::Bool(_)
            | serde_json::Value::Number(_)
            | serde_json::Value::String(_)
    )
}

fn json_to_kdl_value(json: &serde_json::Value) -> KdlValue {
    match json {
        serde_json::Value::Null => KdlValue::Null,
        serde_json::Value::Bool(b) => KdlValue::Bool(*b),
        serde_json::Value::Number(n) => {
            if let Some(i) = n.as_i64() {
                KdlValue::Integer(i as i128)
            } else if let Some(f) = n.as_f64() {
                KdlValue::Float(f)
            } else {
                KdlValue::Null
            }
        }
        serde_json::Value::String(s) => KdlValue::String(s.clone()),
        // Complex values - shouldn't reach here in normal flow
        serde_json::Value::Array(_) | serde_json::Value::Object(_) => {
            KdlValue::String(json.to_string())
        }
    }
}

/// Convert JSON to KDL children with semantic awareness
/// - Arrays become repeated nodes with semantic names
/// - "filters" get special handling
/// - "triggers" get special handling
fn json_to_kdl_children_semantic(json: &serde_json::Value, context: &str) -> KdlDocument {
    let mut doc = KdlDocument::new();

    match json {
        serde_json::Value::Object(obj) => {
            let mut sorted: Vec<_> = obj.iter().collect();
            sorted.sort_by_key(|(k, _)| *k);

            for (key, value) in sorted {
                match value {
                    serde_json::Value::Array(arr) => {
                        // Determine semantic node name based on key
                        let node_name = get_semantic_node_name(key, context);

                        // Create repeated nodes instead of item0, item1
                        for item in arr {
                            let mut item_node = KdlNode::new(node_name.as_str());
                            add_json_to_semantic_node(&mut item_node, item, &node_name);
                            doc.nodes_mut().push(item_node);
                        }
                    }
                    serde_json::Value::Object(_) => {
                        let mut node = KdlNode::new(key.as_str());

                        // Special handling for filters
                        if key == "filters" || key == "filter" {
                            add_filters_to_node(&mut node, value);
                        } else if key == "on_damage" || key == "on_hit" || key == "on_interact" {
                            // Event handlers get semantic children
                            let children = json_to_kdl_children_semantic(value, key);
                            if !children.nodes().is_empty() {
                                node.set_children(children);
                            }
                        } else {
                            // Regular nested object
                            let children = json_to_kdl_children_semantic(value, key);
                            if !children.nodes().is_empty() {
                                node.set_children(children);
                            }
                        }

                        doc.nodes_mut().push(node);
                    }
                    _ => {
                        // Simple value
                        let mut node = KdlNode::new(key.as_str());
                        node.push(KdlEntry::new(json_to_kdl_value(value)));
                        doc.nodes_mut().push(node);
                    }
                }
            }
        }
        serde_json::Value::Array(arr) => {
            let node_name = get_semantic_node_name("item", context);
            for item in arr {
                let mut item_node = KdlNode::new(node_name.as_str());
                add_json_to_semantic_node(&mut item_node, item, &node_name);
                doc.nodes_mut().push(item_node);
            }
        }
        _ => {
            let mut node = KdlNode::new("value");
            node.push(KdlEntry::new(json_to_kdl_value(json)));
            doc.nodes_mut().push(node);
        }
    }

    doc
}

/// Get a semantic node name for array items based on context
fn get_semantic_node_name(key: &str, context: &str) -> String {
    match key {
        "triggers" => "trigger".to_string(),
        "damage_conditions" => "condition".to_string(),
        "interactions" => "interaction".to_string(),
        "event_names" => "event".to_string(),
        "sequences" | "sequence" => "step".to_string(),
        "entries" => "entry".to_string(),
        "pools" => "pool".to_string(),
        "items" => "item".to_string(),
        "functions" => "function".to_string(),
        "conditions" => "condition".to_string(),
        "all_of" => "filter".to_string(),
        "any_of" => "filter".to_string(),
        "none_of" => "filter".to_string(),
        "family" => "family".to_string(),
        "hover_height" | "range" => "range".to_string(),
        _ => {
            // For other arrays, try to singularize or use context
            if key.ends_with("s") && key.len() > 1 {
                key[..key.len()-1].to_string()
            } else if context.ends_with("s") && context.len() > 1 {
                context[..context.len()-1].to_string()
            } else {
                "entry".to_string()
            }
        }
    }
}

/// Add JSON value to a semantic node
fn add_json_to_semantic_node(node: &mut KdlNode, json: &serde_json::Value, node_name: &str) {
    match json {
        serde_json::Value::Object(obj) => {
            let all_simple = obj.values().all(is_simple_value);
            let small_enough = obj.len() <= 6;

            if all_simple && small_enough {
                // Inline as properties
                let mut sorted: Vec<_> = obj.iter().collect();
                sorted.sort_by_key(|(k, _)| *k);
                for (k, v) in sorted {
                    node.push(KdlEntry::new_prop(k.as_str(), json_to_kdl_value(v)));
                }
            } else {
                // Use children
                let children = json_to_kdl_children_semantic(json, node_name);
                if !children.nodes().is_empty() {
                    node.set_children(children);
                }
            }
        }
        _ => {
            node.push(KdlEntry::new(json_to_kdl_value(json)));
        }
    }
}

/// Special handling for Bedrock filter structures
fn add_filters_to_node(node: &mut KdlNode, json: &serde_json::Value) {
    match json {
        serde_json::Value::Object(obj) => {
            // Check for filter group types
            if let Some(all_of) = obj.get("all_of") {
                let mut children = KdlDocument::new();
                if let serde_json::Value::Array(filters) = all_of {
                    for filter in filters {
                        let mut filter_node = KdlNode::new("filter");
                        add_filter_props(&mut filter_node, filter);
                        children.nodes_mut().push(filter_node);
                    }
                }
                node.set_children(children);
            } else if let Some(any_of) = obj.get("any_of") {
                let mut any_node = KdlNode::new("any_of");
                let mut any_children = KdlDocument::new();
                if let serde_json::Value::Array(filters) = any_of {
                    for filter in filters {
                        let mut filter_node = KdlNode::new("filter");
                        add_filter_props(&mut filter_node, filter);
                        any_children.nodes_mut().push(filter_node);
                    }
                }
                any_node.set_children(any_children);

                let mut children = KdlDocument::new();
                children.nodes_mut().push(any_node);
                node.set_children(children);
            } else if let Some(none_of) = obj.get("none_of") {
                let mut none_node = KdlNode::new("none_of");
                let mut none_children = KdlDocument::new();
                if let serde_json::Value::Array(filters) = none_of {
                    for filter in filters {
                        let mut filter_node = KdlNode::new("filter");
                        add_filter_props(&mut filter_node, filter);
                        none_children.nodes_mut().push(filter_node);
                    }
                }
                none_node.set_children(none_children);

                let mut children = KdlDocument::new();
                children.nodes_mut().push(none_node);
                node.set_children(children);
            } else {
                // Single filter - add as properties
                add_filter_props(node, json);
            }
        }
        _ => {}
    }
}

/// Add filter properties to a node
fn add_filter_props(node: &mut KdlNode, json: &serde_json::Value) {
    if let serde_json::Value::Object(obj) = json {
        // Handle nested filter groups
        if obj.contains_key("all_of") || obj.contains_key("any_of") || obj.contains_key("none_of") {
            add_filters_to_node(node, json);
            return;
        }

        // Regular filter - add properties in a logical order
        let order = ["test", "subject", "operator", "domain", "value"];

        for key in order {
            if let Some(v) = obj.get(key) {
                node.push(KdlEntry::new_prop(key, json_to_kdl_value(v)));
            }
        }

        // Add any remaining properties
        for (k, v) in obj {
            if !order.contains(&k.as_str()) {
                node.push(KdlEntry::new_prop(k.as_str(), json_to_kdl_value(v)));
            }
        }
    }
}
