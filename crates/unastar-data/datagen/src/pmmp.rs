//! Normalize vendored PMMP/BedrockData JSON into golden KDL artifacts.

use kdl::{KdlDocument, KdlEntry, KdlNode, KdlValue};
use serde::Deserialize;
use std::collections::HashMap;
use std::path::Path;
use tracing::info;
use walkdir::WalkDir;

use crate::json::remove_json_comments;

const CREATIVE_TABS: [(&str, &str); 4] = [
    ("construction", "creative_construction.json"),
    ("nature", "creative_nature.json"),
    ("equipment", "creative_equipment.json"),
    ("items", "creative_items.json"),
];

/// PMMP calls Bedrock item damage variants `meta`; preserve that source key so
/// variant-bearing creative rows do not collapse into identical item entries.
const CREATIVE_ITEM_PROPERTIES: [&str; 4] = ["meta", "damage", "block_states", "nbt"];

#[derive(Debug, Deserialize)]
struct RequiredItem {
    runtime_id: i32,
    component_based: bool,
    version: i32,
}

#[derive(Debug, Deserialize)]
struct VanillaItemFile {
    #[serde(rename = "minecraft:item")]
    item: VanillaItem,
}

#[derive(Debug, Deserialize)]
struct VanillaItem {
    description: VanillaItemDescription,
    #[serde(default)]
    components: serde_json::Map<String, serde_json::Value>,
}

#[derive(Debug, Deserialize)]
struct VanillaItemDescription {
    identifier: String,
}

#[derive(Debug, Deserialize)]
struct CreativeGroup {
    #[serde(default)]
    group_icon: Option<serde_json::Value>,
    group_name: String,
    items: Vec<serde_json::Value>,
}

pub fn write_pmmp_artifacts(
    pmmp_dir: &Path,
    vanilla_items_dir: &Path,
    output_dir: &Path,
) -> miette::Result<()> {
    write_items_kdl(pmmp_dir, vanilla_items_dir, output_dir)?;
    write_creative_kdl(pmmp_dir, output_dir)?;
    Ok(())
}

fn write_items_kdl(
    pmmp_dir: &Path,
    vanilla_items_dir: &Path,
    output_dir: &Path,
) -> miette::Result<()> {
    let path = pmmp_dir.join("required_item_list.json");
    let content = std::fs::read_to_string(&path)
        .map_err(|e| miette::miette!("Failed to read {}: {}", path.display(), e))?;
    let items: HashMap<String, RequiredItem> = serde_json::from_str(&content)
        .map_err(|e| miette::miette!("Failed to parse {}: {}", path.display(), e))?;
    let stack_sizes = load_vanilla_item_stack_sizes(vanilla_items_dir)?;

    let mut doc = KdlDocument::new();
    let mut names: Vec<_> = items.keys().collect();
    names.sort();

    for name in names {
        let item = &items[name];
        let mut node = KdlNode::new("item");
        node.push(KdlEntry::new(KdlValue::String(name.clone())));
        node.push(KdlEntry::new_prop(
            "runtime_id",
            KdlValue::Integer(item.runtime_id as i128),
        ));
        node.push(KdlEntry::new_prop(
            "component_based",
            KdlValue::Bool(item.component_based),
        ));
        node.push(KdlEntry::new_prop(
            "version",
            KdlValue::Integer(item.version as i128),
        ));
        if let Some(stack_size) = stack_sizes.get(name.as_str()) {
            node.push(KdlEntry::new_prop(
                "max_stack_size",
                KdlValue::Integer(*stack_size as i128),
            ));
            node.push(KdlEntry::new_prop(
                "max_stack_size_source",
                KdlValue::String("vanilla_behavior_pack".to_string()),
            ));
        } else {
            node.push(KdlEntry::new_prop("max_stack_size", KdlValue::Integer(64)));
            node.push(KdlEntry::new_prop(
                "max_stack_size_source",
                KdlValue::String("unsourced_default".to_string()),
            ));
        }
        doc.nodes_mut().push(node);
    }

    write_kdl_with_header(
        output_dir,
        "items.kdl",
        &format!(
            "// AUTO-GENERATED by unastar-data-gen\n\
             // Do not edit manually - changes will be overwritten\n\
             // Source: PMMP/BedrockData required_item_list.json + vanilla behavior-pack item components\n\
             // Item count: {}\n\n",
            items.len()
        ),
        doc,
    )?;

    info!("Wrote {} PMMP item entries", items.len());
    Ok(())
}

fn load_vanilla_item_stack_sizes(items_dir: &Path) -> miette::Result<HashMap<String, u8>> {
    let mut stack_sizes = HashMap::new();
    if !items_dir.exists() {
        return Ok(stack_sizes);
    }

    for entry in WalkDir::new(items_dir) {
        let entry = entry.map_err(|e| miette::miette!("Failed to walk item data: {}", e))?;
        let path = entry.path();
        if !path.is_file() || path.extension().and_then(|ext| ext.to_str()) != Some("json") {
            continue;
        }

        let content = std::fs::read_to_string(path)
            .map_err(|e| miette::miette!("Failed to read {}: {}", path.display(), e))?;
        let stripped = remove_json_comments(&content);
        let item: VanillaItemFile = serde_json::from_str(&stripped)
            .map_err(|e| miette::miette!("Failed to parse {}: {}", path.display(), e))?;

        let Some(stack_size) = item
            .item
            .components
            .get("minecraft:max_stack_size")
            .and_then(|value| value.as_u64())
        else {
            continue;
        };
        let stack_size = u8::try_from(stack_size).map_err(|_| {
            miette::miette!(
                "{} has minecraft:max_stack_size {} outside u8 range",
                path.display(),
                stack_size
            )
        })?;
        if stack_size == 0 {
            return Err(miette::miette!(
                "{} has invalid zero minecraft:max_stack_size",
                path.display()
            ));
        }
        stack_sizes.insert(item.item.description.identifier, stack_size);
    }

    Ok(stack_sizes)
}

fn write_creative_kdl(pmmp_dir: &Path, output_dir: &Path) -> miette::Result<()> {
    let mut doc = KdlDocument::new();
    let mut group_count = 0usize;
    let mut item_count = 0usize;

    for (tab_name, file_name) in CREATIVE_TABS {
        let path = pmmp_dir.join(file_name);
        let content = std::fs::read_to_string(&path)
            .map_err(|e| miette::miette!("Failed to read {}: {}", path.display(), e))?;
        let groups: Vec<CreativeGroup> = serde_json::from_str(&content)
            .map_err(|e| miette::miette!("Failed to parse {}: {}", path.display(), e))?;

        let mut tab = KdlNode::new("creative_tab");
        tab.push(KdlEntry::new(KdlValue::String(tab_name.to_string())));
        tab.push(KdlEntry::new_prop(
            "source_file",
            KdlValue::String(file_name.to_string()),
        ));

        let mut tab_children = KdlDocument::new();
        for (index, group) in groups.iter().enumerate() {
            let mut group_node = KdlNode::new("group");
            group_node.push(KdlEntry::new(KdlValue::String(group.group_name.clone())));
            group_node.push(KdlEntry::new_prop(
                "index",
                KdlValue::Integer(index as i128),
            ));

            let mut group_children = KdlDocument::new();
            if let Some(icon) = &group.group_icon {
                group_children
                    .nodes_mut()
                    .push(item_ref_to_kdl("icon", icon)?);
            }

            for item in &group.items {
                group_children
                    .nodes_mut()
                    .push(item_ref_to_kdl("item", item)?);
                item_count += 1;
            }

            group_node.set_children(group_children);
            tab_children.nodes_mut().push(group_node);
            group_count += 1;
        }

        tab.set_children(tab_children);
        doc.nodes_mut().push(tab);
    }

    write_kdl_with_header(
        output_dir,
        "creative.kdl",
        &format!(
            "// AUTO-GENERATED by unastar-data-gen\n\
             // Do not edit manually - changes will be overwritten\n\
             // Source: PMMP/BedrockData creative inventory JSON\n\
             // Group count: {}\n\
             // Item count: {}\n\n",
            group_count, item_count
        ),
        doc,
    )?;

    info!(
        "Wrote {} PMMP creative groups with {} item entries",
        group_count, item_count
    );
    Ok(())
}

fn item_ref_to_kdl(node_name: &str, value: &serde_json::Value) -> miette::Result<KdlNode> {
    let mut node = KdlNode::new(node_name);
    match value {
        serde_json::Value::String(name) => {
            node.push(KdlEntry::new(KdlValue::String(name.clone())));
        }
        serde_json::Value::Object(object) => {
            let name = object
                .get("name")
                .and_then(|v| v.as_str())
                .ok_or_else(|| miette::miette!("creative item object missing string name"))?;
            node.push(KdlEntry::new(KdlValue::String(name.to_string())));

            for key in object.keys() {
                if key != "name" && !CREATIVE_ITEM_PROPERTIES.contains(&key.as_str()) {
                    return Err(miette::miette!(
                        "unknown PMMP creative item property `{}` for `{}`",
                        key,
                        name
                    ));
                }
            }

            for key in CREATIVE_ITEM_PROPERTIES {
                if let Some(value) = object.get(key) {
                    node.push(KdlEntry::new_prop(key, json_scalar_to_kdl(value)?));
                }
            }
        }
        _ => {
            return Err(miette::miette!(
                "creative item reference must be a string or object"
            ));
        }
    }
    Ok(node)
}

fn json_scalar_to_kdl(value: &serde_json::Value) -> miette::Result<KdlValue> {
    match value {
        serde_json::Value::Bool(v) => Ok(KdlValue::Bool(*v)),
        serde_json::Value::Number(v) => {
            if let Some(i) = v.as_i64() {
                Ok(KdlValue::Integer(i as i128))
            } else if let Some(f) = v.as_f64() {
                Ok(KdlValue::Float(f))
            } else {
                Err(miette::miette!("unsupported JSON number in PMMP data"))
            }
        }
        serde_json::Value::String(v) => Ok(KdlValue::String(v.clone())),
        _ => Err(miette::miette!("expected scalar JSON value in PMMP data")),
    }
}

fn write_kdl_with_header(
    output_dir: &Path,
    file_name: &str,
    header: &str,
    mut doc: KdlDocument,
) -> miette::Result<()> {
    doc.autoformat();
    std::fs::create_dir_all(output_dir)
        .map_err(|e| miette::miette!("Failed to create {}: {}", output_dir.display(), e))?;
    let path = output_dir.join(file_name);
    std::fs::write(&path, format!("{header}{doc}"))
        .map_err(|e| miette::miette!("Failed to write {}: {}", path.display(), e))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn item_ref_accepts_simple_string() {
        let node = item_ref_to_kdl("item", &serde_json::json!("minecraft:stone")).unwrap();
        assert_eq!(node.name().value(), "item");
        assert_eq!(
            node.entries()[0].value().as_string(),
            Some("minecraft:stone")
        );
    }

    #[test]
    fn item_ref_accepts_complex_object() {
        let node = item_ref_to_kdl(
            "item",
            &serde_json::json!({
                "name": "minecraft:cobblestone_wall",
                "meta": 7,
                "damage": 2,
                "block_states": "CgA="
            }),
        )
        .unwrap();

        assert_eq!(
            node.entries()[0].value().as_string(),
            Some("minecraft:cobblestone_wall")
        );
        assert!(node.entries().iter().any(|entry| {
            entry
                .name()
                .is_some_and(|name| name.value() == "block_states")
        }));
        assert!(
            node.entries()
                .iter()
                .any(|entry| entry.name().is_some_and(|name| name.value() == "meta")),
            "PMMP meta variants must not be collapsed"
        );
    }

    #[test]
    fn checked_in_pmmp_artifacts_parse_as_kdl() {
        for (name, content) in [
            ("items.kdl", include_str!("../../output/items.kdl")),
            ("creative.kdl", include_str!("../../output/creative.kdl")),
        ] {
            content
                .parse::<KdlDocument>()
                .unwrap_or_else(|err| panic!("failed to parse generated {name}: {err}"));
        }
    }

    #[test]
    fn items_kdl_merges_behavior_pack_stack_sizes() {
        let temp_dir = std::env::temp_dir().join(format!(
            "unastar-pmmp-items-test-{}-{}",
            std::process::id(),
            unique_suffix()
        ));
        let pmmp_dir = temp_dir.join("pmmp");
        let vanilla_items_dir = temp_dir.join("items");
        let output_dir = temp_dir.join("output");
        std::fs::create_dir_all(&pmmp_dir).expect("create pmmp dir");
        std::fs::create_dir_all(&vanilla_items_dir).expect("create vanilla items dir");
        std::fs::write(
            pmmp_dir.join("required_item_list.json"),
            r#"{
                "minecraft:honey_bottle":{"runtime_id":737,"component_based":false,"version":2},
                "minecraft:stone":{"runtime_id":1,"component_based":false,"version":2}
            }"#,
        )
        .expect("write required item list");
        std::fs::write(
            vanilla_items_dir.join("honey_bottle.json"),
            r#"{
                "minecraft:item":{
                    "description":{"identifier":"minecraft:honey_bottle"},
                    "components":{
                        // JSONC comments from vanilla packs should be accepted.
                        "minecraft:max_stack_size":16
                    }
                }
            }"#,
        )
        .expect("write vanilla item");

        write_items_kdl(&pmmp_dir, &vanilla_items_dir, &output_dir).expect("write items kdl");

        let generated =
            std::fs::read_to_string(output_dir.join("items.kdl")).expect("read items kdl");
        assert!(generated.contains(
            "item minecraft:honey_bottle runtime_id=737 component_based=#false version=2 max_stack_size=16"
        ));
        assert!(generated.contains("max_stack_size_source=vanilla_behavior_pack"));
        assert!(generated.contains(
            "item minecraft:stone runtime_id=1 component_based=#false version=2 max_stack_size=64"
        ));
        assert!(generated.contains("max_stack_size_source=unsourced_default"));

        let _ = std::fs::remove_dir_all(temp_dir);
    }

    #[test]
    fn item_ref_rejects_unknown_object_keys() {
        let err = item_ref_to_kdl(
            "item",
            &serde_json::json!({
                "name": "minecraft:stone",
                "count": 64
            }),
        )
        .unwrap_err();

        assert!(
            err.to_string()
                .contains("unknown PMMP creative item property"),
            "{err:?}"
        );
    }

    fn unique_suffix() -> u128 {
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos()
    }
}
