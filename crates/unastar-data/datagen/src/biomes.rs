//! Normalize vanilla behavior-pack biome JSON into a golden KDL artifact.
//!
//! Biome gameplay semantics should come from the data-driven behavior-pack
//! definitions first. Valentine/Prismarine biome tables are useful protocol
//! fallbacks, but are intentionally not used here as canonical gameplay data.

use kdl::{KdlDocument, KdlEntry, KdlNode, KdlValue};
use serde::Deserialize;
use std::collections::HashMap;
use std::path::Path;
use tracing::{debug, info};
use walkdir::WalkDir;

use crate::json::remove_json_comments;

#[derive(Debug, Deserialize)]
struct RawBiomeFile {
    format_version: String,
    #[serde(rename = "minecraft:biome")]
    biome: RawBiome,
}

#[derive(Debug, Deserialize)]
struct RawBiome {
    description: RawBiomeDescription,
    #[serde(default)]
    components: HashMap<String, serde_json::Value>,
}

#[derive(Debug, Deserialize)]
struct RawBiomeDescription {
    identifier: String,
}

#[derive(Debug)]
struct BiomeArtifact {
    format_version: String,
    identifier: String,
    source_file: String,
    components: HashMap<String, serde_json::Value>,
}

pub fn write_biomes_kdl(biomes_dir: &Path, output_dir: &Path) -> miette::Result<()> {
    let biomes = parse_biomes(biomes_dir)?;
    let mut doc = KdlDocument::new();

    for biome in &biomes {
        let mut node = KdlNode::new("biome");
        node.push(KdlEntry::new(KdlValue::String(biome.identifier.clone())));
        node.push(KdlEntry::new_prop(
            "format_version",
            KdlValue::String(biome.format_version.clone()),
        ));
        node.push(KdlEntry::new_prop(
            "source",
            KdlValue::String("vanilla_behavior_pack".to_string()),
        ));
        node.push(KdlEntry::new_prop(
            "source_file",
            KdlValue::String(biome.source_file.clone()),
        ));

        let mut children = KdlDocument::new();
        let mut component_names: Vec<_> = biome.components.keys().collect();
        component_names.sort();

        for component_name in component_names {
            let component = &biome.components[component_name];
            let mut component_node = KdlNode::new("component");
            component_node.push(KdlEntry::new(KdlValue::String(component_name.clone())));

            let component_children = json_to_kdl_children(component, component_name);
            if !component_children.nodes().is_empty() {
                component_node.set_children(component_children);
            }
            children.nodes_mut().push(component_node);
        }

        node.set_children(children);
        doc.nodes_mut().push(node);
    }

    write_kdl_with_header(
        output_dir,
        &format!(
            "// AUTO-GENERATED by unastar-data-gen\n\
             // Do not edit manually - changes will be overwritten\n\
             // Source: vanilla behavior-pack biome JSON\n\
             // Biome count: {}\n\n",
            biomes.len()
        ),
        doc,
    )?;

    info!("Wrote {} vanilla behavior-pack biome entries", biomes.len());
    Ok(())
}

fn parse_biomes(biomes_dir: &Path) -> miette::Result<Vec<BiomeArtifact>> {
    if !biomes_dir.exists() {
        return Err(miette::miette!(
            "Vanilla biome directory does not exist: {}",
            biomes_dir.display()
        ));
    }

    let mut biomes = Vec::new();

    for entry in WalkDir::new(biomes_dir)
        .into_iter()
        .filter_map(Result::ok)
        .filter(|entry| {
            entry.file_type().is_file()
                && entry
                    .path()
                    .extension()
                    .is_some_and(|extension| extension == "json")
        })
    {
        debug!("Parsing vanilla biome: {}", entry.path().display());
        biomes.push(parse_biome_file(biomes_dir, entry.path())?);
    }

    biomes.sort_by(|a, b| a.identifier.cmp(&b.identifier));
    Ok(biomes)
}

fn parse_biome_file(root: &Path, path: &Path) -> miette::Result<BiomeArtifact> {
    let content = std::fs::read_to_string(path)
        .map_err(|e| miette::miette!("Failed to read {}: {}", path.display(), e))?;
    let content = remove_json_comments(&content);
    let raw: RawBiomeFile = serde_json::from_str(&content)
        .map_err(|e| miette::miette!("Failed to parse {}: {}", path.display(), e))?;

    Ok(BiomeArtifact {
        format_version: raw.format_version,
        identifier: raw.biome.description.identifier,
        source_file: normalize_source_file(root, path),
        components: raw.biome.components,
    })
}

fn normalize_source_file(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

fn json_to_kdl_children(value: &serde_json::Value, context: &str) -> KdlDocument {
    let mut doc = KdlDocument::new();
    match value {
        serde_json::Value::Object(object) => {
            let mut keys: Vec<_> = object.keys().collect();
            keys.sort();
            for key in keys {
                let child = json_entry_to_kdl_node(key, &object[key], key);
                doc.nodes_mut().push(child);
            }
        }
        serde_json::Value::Array(values) => {
            for value in values {
                doc.nodes_mut().push(json_entry_to_kdl_node(
                    array_item_name(context),
                    value,
                    context,
                ));
            }
        }
        scalar => {
            let mut node = KdlNode::new("value");
            node.push(KdlEntry::new(json_scalar_to_kdl(scalar)));
            doc.nodes_mut().push(node);
        }
    }
    doc
}

fn json_entry_to_kdl_node(name: &str, value: &serde_json::Value, context: &str) -> KdlNode {
    let mut node = KdlNode::new(name);
    match value {
        serde_json::Value::Object(_) | serde_json::Value::Array(_) => {
            let children = json_to_kdl_children(value, context);
            if !children.nodes().is_empty() {
                node.set_children(children);
            }
        }
        scalar => {
            node.push(KdlEntry::new(json_scalar_to_kdl(scalar)));
        }
    }
    node
}

fn array_item_name(context: &str) -> &'static str {
    match context {
        "tags" => "tag",
        "adjustments" => "adjustment",
        "generate_for_climates" => "climate_weight",
        "hills_transformation" | "shore_transformation" => "transformation_weight",
        _ => "item",
    }
}

fn json_scalar_to_kdl(value: &serde_json::Value) -> KdlValue {
    match value {
        serde_json::Value::Null => KdlValue::Null,
        serde_json::Value::Bool(value) => KdlValue::Bool(*value),
        serde_json::Value::Number(value) => {
            if let Some(integer) = value.as_i64() {
                KdlValue::Integer(integer as i128)
            } else if let Some(float) = value.as_f64() {
                KdlValue::Float(readable_f64(float))
            } else {
                KdlValue::Null
            }
        }
        serde_json::Value::String(value) => KdlValue::String(value.clone()),
        serde_json::Value::Array(_) | serde_json::Value::Object(_) => {
            KdlValue::String(value.to_string())
        }
    }
}

fn readable_f64(value: f64) -> f64 {
    (value * 1_000_000.0).round() / 1_000_000.0
}

fn write_kdl_with_header(
    output_dir: &Path,
    header: &str,
    mut doc: KdlDocument,
) -> miette::Result<()> {
    doc.autoformat();
    std::fs::create_dir_all(output_dir)
        .map_err(|e| miette::miette!("Failed to create {}: {}", output_dir.display(), e))?;
    let path = output_dir.join("biomes.kdl");
    std::fs::write(&path, format!("{header}{doc}"))
        .map_err(|e| miette::miette!("Failed to write {}: {}", path.display(), e))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn vanilla_biomes_dir() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../data/vanilla_bp/behavior_pack/biomes")
    }

    #[test]
    fn parses_checked_in_vanilla_biomes() {
        let biomes = parse_biomes(&vanilla_biomes_dir()).expect("parse biomes");

        assert_eq!(biomes.len(), 87);
        assert!(biomes.iter().any(|biome| {
            biome.identifier == "minecraft:plains"
                && biome.components.contains_key("minecraft:climate")
                && biome.components.contains_key("minecraft:tags")
        }));
    }

    #[test]
    fn checked_in_biomes_artifact_parses_as_kdl() {
        include_str!("../../output/biomes.kdl")
            .parse::<KdlDocument>()
            .expect("generated biomes.kdl should parse");
    }

    #[test]
    fn checked_in_biomes_artifact_uses_behavior_pack_source() {
        let artifact = include_str!("../../output/biomes.kdl");

        assert!(artifact.contains("Source: vanilla behavior-pack biome JSON"));
        assert!(artifact.contains("source=vanilla_behavior_pack"));
        assert!(!artifact.contains("valentine_bedrock_1_26_0"));
    }
}
