//! Normalize protocolgen native biome IDs/definitions with behavior-pack gameplay semantics.
//! Native data owns the registry and climate. Behavior-pack components retain their
//! explicit provenance; new native-only biomes have no invented gameplay components.

use kdl::{KdlDocument, KdlEntry, KdlNode, KdlValue};
use serde::Deserialize;
use std::collections::{BTreeMap, HashMap, HashSet};
use std::path::Path;
use tracing::{debug, info};
use walkdir::WalkDir;

use crate::json::remove_json_comments;

#[derive(Debug, Deserialize)]
struct RawBiomeFile {
    format_version: String,
    #[serde(rename = "minecraft:biome")]
    biome: RawBiome,
}

#[derive(Debug, Deserialize)]
struct RawBiome {
    description: RawBiomeDescription,
    #[serde(default)]
    components: HashMap<String, serde_json::Value>,
}

#[derive(Debug, Deserialize)]
struct RawBiomeDescription {
    identifier: String,
}

#[derive(Debug)]
struct BiomeArtifact {
    id: u32,
    definition: serde_json::Value,
    format_version: String,
    identifier: String,
    source_file: String,
    components: HashMap<String, serde_json::Value>,
}

pub fn write_biomes_kdl(
    native_dir: &Path,
    biomes_dir: &Path,
    output_dir: &Path,
) -> miette::Result<()> {
    let biomes = load_biomes(native_dir, biomes_dir)?;
    let mut doc = KdlDocument::new();

    for biome in &biomes {
        let mut node = KdlNode::new("biome");
        node.push(KdlEntry::new(KdlValue::String(biome.identifier.clone())));
        node.push(KdlEntry::new_prop(
            "format_version",
            KdlValue::String(biome.format_version.clone()),
        ));
        node.push(KdlEntry::new_prop(
            "source",
            KdlValue::String("protocolgen_native".to_string()),
        ));
        node.push(KdlEntry::new_prop(
            "source_file",
            KdlValue::String(biome.source_file.clone()),
        ));
        node.push(KdlEntry::new_prop(
            "id",
            KdlValue::Integer(biome.id as i128),
        ));
        node.push(KdlEntry::new_prop(
            "native_definition",
            KdlValue::String(biome.definition.to_string()),
        ));
        node.push(KdlEntry::new_prop(
            "components_source",
            KdlValue::String("vanilla_behavior_pack".to_string()),
        ));

        let mut children = KdlDocument::new();
        let mut component_names: Vec<_> = biome.components.keys().collect();
        component_names.sort();

        for component_name in component_names {
            let component = &biome.components[component_name];
            let mut component_node = KdlNode::new("component");
            component_node.push(KdlEntry::new(KdlValue::String(component_name.clone())));
            component_node.push(KdlEntry::new_prop(
                "source",
                KdlValue::String("vanilla_behavior_pack".to_string()),
            ));

            let component_children = json_to_kdl_children(component, component_name);
            if !component_children.nodes().is_empty() {
                component_node.set_children(component_children);
            }
            children.nodes_mut().push(component_node);
        }

        node.set_children(children);
        doc.nodes_mut().push(node);
    }

    write_kdl_with_header(
        output_dir,
        &format!(
            "// AUTO-GENERATED by unastar-data-gen\n\
             // Do not edit manually - changes will be overwritten\n\
             // Source: protocolgen native biome IDs and definitions; vanilla behavior-pack gameplay components\n\
             // Biome count: {}\n\n",
            biomes.len()
        ),
        doc,
    )?;

    info!(
        "Wrote {} native biome entries with behavior-pack gameplay components",
        biomes.len()
    );
    Ok(())
}

fn load_biomes(native_dir: &Path, biomes_dir: &Path) -> miette::Result<Vec<BiomeArtifact>> {
    fn read_json<T: serde::de::DeserializeOwned>(path: &Path) -> miette::Result<T> {
        let content = std::fs::read_to_string(path)
            .map_err(|e| miette::miette!("Failed to read {}: {}", path.display(), e))?;
        serde_json::from_str(&content)
            .map_err(|e| miette::miette!("Failed to parse {}: {}", path.display(), e))
    }
    merge_biomes(
        read_json(&native_dir.join("biome_id_map.json"))?,
        read_json(&native_dir.join("biome_definitions.json"))?,
        parse_biomes(biomes_dir)?,
    )
}

fn merge_biomes(
    ids: BTreeMap<String, u32>,
    mut definitions: BTreeMap<String, serde_json::Value>,
    gameplay: Vec<BiomeArtifact>,
) -> miette::Result<Vec<BiomeArtifact>> {
    if ids.is_empty() {
        return Err(miette::miette!("native biome ID map is empty"));
    }
    let mut seen_ids = HashSet::new();
    for id in ids.values() {
        if !seen_ids.insert(*id) {
            return Err(miette::miette!("duplicate native biome ID: {}", id));
        }
    }
    let mut components = HashMap::new();
    for biome in gameplay {
        let identifier = biome.identifier.clone();
        if components.insert(identifier.clone(), biome).is_some() {
            return Err(miette::miette!(
                "duplicate behavior-pack biome: {}",
                identifier
            ));
        }
        if !ids.contains_key(&identifier) {
            return Err(miette::miette!(
                "behavior-pack biome {} missing native ID",
                identifier
            ));
        }
    }
    let mut result = Vec::with_capacity(ids.len());
    for (identifier, id) in ids {
        let definition = definitions
            .remove(&identifier)
            .ok_or_else(|| miette::miette!("{} missing native definition", identifier))?;
        for field in [
            "temperature",
            "downfall",
            "redSporeDensity",
            "blueSporeDensity",
            "ashDensity",
            "whiteAshDensity",
            "snowAccumulation",
            "foliageSnow",
            "minSnowLevel",
            "maxSnowLevel",
            "depth",
            "scale",
            "waterTransparency",
        ] {
            if definition
                .get(field)
                .and_then(serde_json::Value::as_f64)
                .is_none()
            {
                return Err(miette::miette!(
                    "{} missing native numeric {}",
                    identifier,
                    field
                ));
            }
        }
        if definition
            .get("rain")
            .and_then(serde_json::Value::as_bool)
            .is_none()
            || definition
                .get("mapWaterColor")
                .and_then(serde_json::Value::as_str)
                .is_none()
        {
            return Err(miette::miette!(
                "{} missing native rain or mapWaterColor",
                identifier
            ));
        }
        let mut biome = components
            .remove(&identifier)
            .unwrap_or_else(|| BiomeArtifact {
                id,
                definition: serde_json::Value::Null,
                identifier,
                // Native-only entries have no behavior-pack format or source file.
                format_version: String::new(),
                source_file: String::new(),
                components: HashMap::new(),
            });
        biome.id = id;
        biome.definition = definition;
        result.push(biome);
    }
    if !definitions.is_empty() {
        return Err(miette::miette!(
            "native biome definitions missing IDs: {:?}",
            definitions.keys()
        ));
    }
    Ok(result)
}

fn parse_biomes(biomes_dir: &Path) -> miette::Result<Vec<BiomeArtifact>> {
    if !biomes_dir.exists() {
        return Err(miette::miette!(
            "Vanilla biome directory does not exist: {}",
            biomes_dir.display()
        ));
    }

    let mut biomes = Vec::new();

    for entry in WalkDir::new(biomes_dir)
        .into_iter()
        .filter_map(Result::ok)
        .filter(|entry| {
            entry.file_type().is_file()
                && entry
                    .path()
                    .extension()
                    .is_some_and(|extension| extension == "json")
        })
    {
        debug!("Parsing vanilla biome: {}", entry.path().display());
        biomes.push(parse_biome_file(biomes_dir, entry.path())?);
    }

    biomes.sort_by(|a, b| a.identifier.cmp(&b.identifier));
    Ok(biomes)
}

fn parse_biome_file(root: &Path, path: &Path) -> miette::Result<BiomeArtifact> {
    let content = std::fs::read_to_string(path)
        .map_err(|e| miette::miette!("Failed to read {}: {}", path.display(), e))?;
    let content = remove_json_comments(&content);
    let raw: RawBiomeFile = serde_json::from_str(&content)
        .map_err(|e| miette::miette!("Failed to parse {}: {}", path.display(), e))?;

    Ok(BiomeArtifact {
        id: 0,
        definition: serde_json::Value::Null,
        format_version: raw.format_version,
        identifier: raw.biome.description.identifier,
        source_file: normalize_source_file(root, path),
        components: raw.biome.components,
    })
}

fn normalize_source_file(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

fn json_to_kdl_children(value: &serde_json::Value, context: &str) -> KdlDocument {
    let mut doc = KdlDocument::new();
    match value {
        serde_json::Value::Object(object) => {
            let mut keys: Vec<_> = object.keys().collect();
            keys.sort();
            for key in keys {
                let child = json_entry_to_kdl_node(key, &object[key], key);
                doc.nodes_mut().push(child);
            }
        }
        serde_json::Value::Array(values) => {
            for value in values {
                doc.nodes_mut().push(json_entry_to_kdl_node(
                    array_item_name(context),
                    value,
                    context,
                ));
            }
        }
        scalar => {
            let mut node = KdlNode::new("value");
            node.push(KdlEntry::new(json_scalar_to_kdl(scalar)));
            doc.nodes_mut().push(node);
        }
    }
    doc
}

fn json_entry_to_kdl_node(name: &str, value: &serde_json::Value, context: &str) -> KdlNode {
    let mut node = KdlNode::new(name);
    match value {
        serde_json::Value::Object(_) | serde_json::Value::Array(_) => {
            let children = json_to_kdl_children(value, context);
            if !children.nodes().is_empty() {
                node.set_children(children);
            }
        }
        scalar => {
            node.push(KdlEntry::new(json_scalar_to_kdl(scalar)));
        }
    }
    node
}

fn array_item_name(context: &str) -> &'static str {
    match context {
        "tags" => "tag",
        "adjustments" => "adjustment",
        "generate_for_climates" => "climate_weight",
        "hills_transformation" | "shore_transformation" => "transformation_weight",
        _ => "item",
    }
}

fn json_scalar_to_kdl(value: &serde_json::Value) -> KdlValue {
    match value {
        serde_json::Value::Null => KdlValue::Null,
        serde_json::Value::Bool(value) => KdlValue::Bool(*value),
        serde_json::Value::Number(value) => {
            if let Some(integer) = value.as_i64() {
                KdlValue::Integer(integer as i128)
            } else if let Some(float) = value.as_f64() {
                KdlValue::Float(readable_f64(float))
            } else {
                KdlValue::Null
            }
        }
        serde_json::Value::String(value) => KdlValue::String(value.clone()),
        serde_json::Value::Array(_) | serde_json::Value::Object(_) => {
            KdlValue::String(value.to_string())
        }
    }
}

fn readable_f64(value: f64) -> f64 {
    (value * 1_000_000.0).round() / 1_000_000.0
}

fn write_kdl_with_header(
    output_dir: &Path,
    header: &str,
    mut doc: KdlDocument,
) -> miette::Result<()> {
    doc.autoformat();
    std::fs::create_dir_all(output_dir)
        .map_err(|e| miette::miette!("Failed to create {}: {}", output_dir.display(), e))?;
    let path = output_dir.join("biomes.kdl");
    std::fs::write(&path, format!("{header}{doc}"))
        .map_err(|e| miette::miette!("Failed to write {}: {}", path.display(), e))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn vanilla_biomes_dir() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../data/vanilla_bp/behavior_pack/biomes")
    }

    #[test]
    fn parses_checked_in_vanilla_biomes() {
        let biomes = parse_biomes(&vanilla_biomes_dir()).expect("parse biomes");

        // bedrock-samples 1.26.50.4 ships a file for each of BDS's 89 biomes
        // (1.21.130.3 had 87: no dappled_forest or sulfur_caves).
        assert_eq!(biomes.len(), 89);
        assert!(biomes.iter().any(|biome| {
            biome.identifier == "minecraft:plains"
                && biome.components.contains_key("minecraft:climate")
                && biome.components.contains_key("minecraft:tags")
        }));
    }

    #[test]
    fn checked_in_biomes_artifact_parses_as_kdl() {
        include_str!("../../output/biomes.kdl")
            .parse::<KdlDocument>()
            .expect("generated biomes.kdl should parse");
    }

    #[test]
    fn native_biomes_include_new_ids_and_preserve_gameplay_components() {
        let native = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../../valentine_gen/protocolgen/data/source/inputs/1.26.51/native");
        let biomes = load_biomes(&native, &vanilla_biomes_dir()).expect("native biomes");
        assert_eq!(biomes.len(), 89);
        assert!(
            biomes
                .windows(2)
                .all(|pair| pair[0].identifier < pair[1].identifier)
        );
        let dappled = biomes
            .iter()
            .find(|b| b.identifier == "minecraft:dappled_forest")
            .unwrap();
        assert_eq!(dappled.id, 195);
        assert!(dappled.definition["temperature"].is_number());
        let plains = biomes
            .iter()
            .find(|b| b.identifier == "minecraft:plains")
            .unwrap();
        assert_eq!(plains.id, 1);
        assert!(plains.components.contains_key("minecraft:tags"));
    }

    #[test]
    fn native_join_rejects_missing_definitions_and_duplicate_ids() {
        let ids = serde_json::from_str(r#"{"minecraft:a":1}"#).unwrap();
        let error = merge_biomes(ids, Default::default(), Vec::new()).unwrap_err();
        assert!(error.to_string().contains("missing native definition"));
        let ids = serde_json::from_str(r#"{"minecraft:a":1,"minecraft:b":1}"#).unwrap();
        let definitions = serde_json::from_str(
            r#"{"minecraft:a":{"temperature":1,"downfall":0},"minecraft:b":{"temperature":1,"downfall":0}}"#,
        ).unwrap();
        assert!(
            merge_biomes(ids, definitions, Vec::new())
                .unwrap_err()
                .to_string()
                .contains("duplicate native biome ID")
        );
    }
}
