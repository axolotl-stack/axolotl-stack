//! Normalize `bds-extractor` JSON captures into packet-facing KDL artifacts.
//!
//! This lane is intentionally separate from behavior-pack biome semantics:
//! live BDS captures own packet/runtime IDs, while `biomes.kdl` owns exposed
//! data-driven biome components and tags.

use kdl::{KdlDocument, KdlEntry, KdlNode, KdlValue};
use serde::Deserialize;
use std::path::Path;
use tracing::info;

#[derive(Debug, Deserialize)]
struct ExtractedData {
    metadata: Metadata,
    #[serde(default)]
    biomes: Option<BiomeData>,
}

#[derive(Debug, Deserialize)]
struct Metadata {
    extraction_date: String,
    game_version: String,
    engine: String,
}

#[derive(Debug, Deserialize)]
struct BiomeData {
    definitions: Vec<BiomeDefinition>,
    string_list: Vec<String>,
}

#[derive(Debug, Deserialize)]
struct BiomeDefinition {
    name_index: i16,
    biome_id: u16,
    temperature: f32,
    downfall: f32,
}

#[derive(Debug)]
struct NormalizedBiomeDefinition {
    identifier: String,
    name_index: i16,
    biome_id: u16,
    temperature: f32,
    downfall: f32,
}

pub fn write_bds_artifacts(extraction_path: &Path, output_dir: &Path) -> miette::Result<()> {
    write_biome_packets_kdl(extraction_path, output_dir)
}

pub fn extraction_version(extraction_path: &Path) -> miette::Result<Option<String>> {
    let data = read_extracted_data(extraction_path)?;
    if data.metadata.engine.trim().is_empty() {
        return Err(miette::miette!(
            "{} has empty BDS extractor metadata.engine",
            extraction_path.display()
        ));
    }
    if data.metadata.game_version.trim().is_empty() {
        return Err(miette::miette!(
            "{} has empty BDS extractor metadata.game_version",
            extraction_path.display()
        ));
    }
    Ok(Some(format!(
        "{}:{}",
        data.metadata.engine, data.metadata.game_version
    )))
}

fn write_biome_packets_kdl(extraction_path: &Path, output_dir: &Path) -> miette::Result<()> {
    let data = read_extracted_data(extraction_path)?;
    let Some(biomes) = data.biomes else {
        return Err(miette::miette!(
            "{} does not contain BDS biome definitions",
            extraction_path.display()
        ));
    };
    let definitions = normalize_biome_definitions(&biomes)?;

    let mut doc = KdlDocument::new();
    for definition in &definitions {
        let mut node = KdlNode::new("biome_packet");
        node.push(KdlEntry::new(KdlValue::String(
            definition.identifier.clone(),
        )));
        node.push(KdlEntry::new_prop(
            "source",
            KdlValue::String("bds_extractor".to_string()),
        ));
        node.push(KdlEntry::new_prop(
            "biome_id",
            KdlValue::Integer(definition.biome_id as i128),
        ));
        node.push(KdlEntry::new_prop(
            "name_index",
            KdlValue::Integer(definition.name_index as i128),
        ));
        node.push(KdlEntry::new_prop(
            "temperature",
            KdlValue::Float(readable_f32(definition.temperature)),
        ));
        node.push(KdlEntry::new_prop(
            "downfall",
            KdlValue::Float(readable_f32(definition.downfall)),
        ));
        doc.nodes_mut().push(node);
    }

    write_kdl_with_header(
        output_dir,
        &format!(
            "// AUTO-GENERATED by unastar-data-gen\n\
             // Do not edit manually - changes will be overwritten\n\
             // Source: bds-extractor JSON capture\n\
             // Engine: {}\n\
             // Game version: {}\n\
             // Extraction date: {}\n\
             // Biome packet count: {}\n\n",
            data.metadata.engine,
            data.metadata.game_version,
            data.metadata.extraction_date,
            definitions.len()
        ),
        doc,
    )?;

    info!(
        "Wrote {} BDS biome packet definitions from {}",
        definitions.len(),
        extraction_path.display()
    );
    Ok(())
}

fn read_extracted_data(path: &Path) -> miette::Result<ExtractedData> {
    let content = std::fs::read_to_string(path)
        .map_err(|e| miette::miette!("Failed to read {}: {}", path.display(), e))?;
    serde_json::from_str(&content)
        .map_err(|e| miette::miette!("Failed to parse {}: {}", path.display(), e))
}

fn normalize_biome_definitions(
    biomes: &BiomeData,
) -> miette::Result<Vec<NormalizedBiomeDefinition>> {
    if biomes.definitions.is_empty() {
        return Err(miette::miette!(
            "BDS biome definitions must not be empty when present"
        ));
    }
    if biomes.string_list.is_empty() {
        return Err(miette::miette!(
            "BDS biome string_list must not be empty when definitions are present"
        ));
    }

    let mut definitions = Vec::with_capacity(biomes.definitions.len());
    for definition in &biomes.definitions {
        let name_index = usize::try_from(definition.name_index).map_err(|_| {
            miette::miette!(
                "BDS biome {} has negative name_index {}",
                definition.biome_id,
                definition.name_index
            )
        })?;
        let identifier = biomes.string_list.get(name_index).ok_or_else(|| {
            miette::miette!(
                "BDS biome {} name_index {} is out of range for string_list length {}",
                definition.biome_id,
                definition.name_index,
                biomes.string_list.len()
            )
        })?;
        if identifier.trim().is_empty() {
            return Err(miette::miette!(
                "BDS biome {} resolved to an empty identifier",
                definition.biome_id
            ));
        }
        if !definition.temperature.is_finite() || !definition.downfall.is_finite() {
            return Err(miette::miette!(
                "BDS biome {} has non-finite climate values",
                definition.biome_id
            ));
        }

        definitions.push(NormalizedBiomeDefinition {
            identifier: identifier.clone(),
            name_index: definition.name_index,
            biome_id: definition.biome_id,
            temperature: definition.temperature,
            downfall: definition.downfall,
        });
    }

    definitions.sort_by(|a, b| {
        a.biome_id
            .cmp(&b.biome_id)
            .then_with(|| a.identifier.cmp(&b.identifier))
    });
    Ok(definitions)
}

fn write_kdl_with_header(
    output_dir: &Path,
    header: &str,
    mut doc: KdlDocument,
) -> miette::Result<()> {
    doc.autoformat();
    std::fs::create_dir_all(output_dir)
        .map_err(|e| miette::miette!("Failed to create {}: {}", output_dir.display(), e))?;
    let path = output_dir.join("biome_packets.kdl");
    std::fs::write(&path, format!("{header}{doc}"))
        .map_err(|e| miette::miette!("Failed to write {}: {}", path.display(), e))?;
    Ok(())
}

fn readable_f32(value: f32) -> f64 {
    ((value as f64) * 1_000_000.0).round() / 1_000_000.0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn normalizes_biome_definitions_by_packet_id() {
        let definitions = normalize_biome_definitions(&BiomeData {
            definitions: vec![
                BiomeDefinition {
                    name_index: 1,
                    biome_id: 2,
                    temperature: 0.5,
                    downfall: 0.6,
                },
                BiomeDefinition {
                    name_index: 0,
                    biome_id: 1,
                    temperature: 0.8,
                    downfall: 0.4,
                },
            ],
            string_list: vec![
                "minecraft:plains".to_string(),
                "minecraft:forest".to_string(),
            ],
        })
        .expect("normalize biome definitions");

        assert_eq!(definitions[0].identifier, "minecraft:plains");
        assert_eq!(definitions[0].biome_id, 1);
        assert_eq!(definitions[1].identifier, "minecraft:forest");
    }

    #[test]
    fn rejects_out_of_range_biome_name_index() {
        let err = normalize_biome_definitions(&BiomeData {
            definitions: vec![BiomeDefinition {
                name_index: 3,
                biome_id: 1,
                temperature: 0.8,
                downfall: 0.4,
            }],
            string_list: vec!["minecraft:plains".to_string()],
        })
        .unwrap_err();

        assert!(err.to_string().contains("out of range"));
    }

    #[test]
    fn writes_biome_packets_kdl_from_extractor_json() {
        let temp_dir = std::env::temp_dir().join(format!(
            "unastar-data-bds-test-{}-{}",
            std::process::id(),
            unique_suffix()
        ));
        std::fs::create_dir_all(&temp_dir).expect("create temp dir");
        let input = temp_dir.join("capture.json");
        let output = temp_dir.join("out");
        std::fs::write(
            &input,
            r#"{
                "metadata": {
                    "extraction_date": "fixture",
                    "game_version": "1.26.0",
                    "engine": "BDS"
                },
                "biomes": {
                    "definitions": [
                        {
                            "name_index": 0,
                            "biome_id": 1,
                            "temperature": 0.8,
                            "downfall": 0.4
                        }
                    ],
                    "string_list": ["minecraft:plains"]
                }
            }"#,
        )
        .expect("write input");

        write_bds_artifacts(&input, &output).expect("write bds artifacts");
        let artifact =
            std::fs::read_to_string(output.join("biome_packets.kdl")).expect("read artifact");
        artifact
            .parse::<KdlDocument>()
            .expect("generated biome_packets.kdl should parse");
        assert!(artifact.contains("source=bds_extractor"));
        assert!(artifact.contains("biome_id=1"));
        assert!(artifact.contains("temperature=0.8"));

        let _ = std::fs::remove_dir_all(temp_dir);
    }

    #[test]
    fn extraction_version_rejects_empty_version_metadata() {
        let temp_dir = std::env::temp_dir().join(format!(
            "unastar-bds-version-test-{}-{}",
            std::process::id(),
            unique_suffix()
        ));
        std::fs::create_dir_all(&temp_dir).expect("create temp dir");
        let input = temp_dir.join("capture.json");
        std::fs::write(
            &input,
            r#"{
                "metadata": {
                    "extraction_date": "fixture",
                    "game_version": "",
                    "engine": "BDS"
                }
            }"#,
        )
        .expect("write input");

        let err = extraction_version(&input).expect_err("empty version is invalid");

        assert!(err.to_string().contains("metadata.game_version"));
        let _ = std::fs::remove_dir_all(temp_dir);
    }

    fn unique_suffix() -> u128 {
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos()
    }
}
