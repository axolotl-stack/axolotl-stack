//! Typed spawn-rule bodies and the canonical vanilla spawn rules (D2).
//!
//! The bodies are generated from the pinned `server/spawn` schemas with the
//! actor component lowering ([`crate::actor_components::schema_items`]):
//! `Spawn Rules.json` is the `minecraft:spawn_rules` object, each condition
//! is a `SpawnBiomeConditions` whose fields are the condition components
//! (`minecraft:herd` → `herd`). The vanilla documents are read from the
//! pinned pack (comments stripped) and embedded as canonical JSON; the
//! runtime decodes them once into the generated types.

use std::path::Path;

use quote::quote;
use serde_json::{Value, json};
use unastar_packs::packs::{Family, PackStack};

/// The pinned spawn schema version (the only one published).
const SCHEMA_VERSION: &str = "1.21.50";

pub fn write(pack: &Path, out: &Path) {
    let schema_dir = pack
        .parent()
        .expect("behavior_pack parent")
        .join("metadata/json_schemas/server/spawn")
        .join(SCHEMA_VERSION);
    println!("cargo:rerun-if-changed={}", schema_dir.display());
    let items = crate::actor_components::schema_items(&schema_dir.join("Spawn Rules.json"));
    let body = items.tokens;
    let tokens = quote! {
        pub mod body {
            use crate::actor_components::FilterJson;
            use serde::Deserialize;

            #body
        }
    };
    let file = syn::parse2::<syn::File>(tokens).expect("generated spawn rules parse");
    let mut source = format!(
        "// @generated by crates/unastar-data/build/spawn_rules.rs from the pinned\n\
         // server/spawn/{SCHEMA_VERSION} schemas. Do not edit.\n\
         // {} generated types.\n\
         // Untyped schema nodes lowered to serde_json::Value: {}\n",
        items.types,
        items.holes.len(),
    );
    for hole in &items.holes {
        source.push_str(&format!("//   - {hole}\n"));
    }
    source.push('\n');
    source.push_str(&prettyplease::unparse(&file));
    std::fs::write(out.join("spawn_rules.rs"), source).expect("writing spawn rule bodies");

    let stack = PackStack::single_pack("bedrock-samples", pack);
    println!(
        "cargo:rerun-if-changed={}",
        pack.join("spawn_rules").display()
    );
    for input in stack.inputs(Family::SpawnRules) {
        println!("cargo:rerun-if-changed={}", input.display());
    }
    let mut rows: Vec<Value> = stack
        .files(Family::SpawnRules)
        .expect("reading vanilla spawn rules")
        .into_iter()
        .map(|file| {
            let document = unastar_packs::json::parse(&file.origin, &file.bytes)
                .unwrap_or_else(|e| panic!("{e}"));
            json!({ "source": file.entry, "document": document })
        })
        .collect();
    assert!(!rows.is_empty(), "vanilla spawn rules are empty");
    rows.sort_by(|a, b| a["source"].as_str().cmp(&b["source"].as_str()));
    std::fs::write(
        out.join("spawn_rules.json"),
        serde_json::to_vec(&rows).expect("spawn rules serialize"),
    )
    .expect("writing canonical embedded spawn rules");
}
