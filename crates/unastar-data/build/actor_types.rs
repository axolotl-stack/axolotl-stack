//! The [`ActorType`] enum: one variant per actor identifier BDS advertises in
//! the captured `AvailableActorIdentifiers` list
//! (`output/actor_identifiers.json`), named like `ActorComponent` variants
//! (`minecraft:` stripped, UpperCamelCase), in identifier order. Native actor
//! class behaviour is keyed by this type instead of identifier strings.

use std::path::Path;

use quote::{format_ident, quote};

pub fn write(identifiers: &Path, out: &Path) {
    println!("cargo:rerun-if-changed={}", identifiers.display());
    let text = std::fs::read_to_string(identifiers).expect("reading captured actor identifiers");
    let artifact: serde_json::Value =
        serde_json::from_str(&text).expect("captured actor identifiers are JSON");
    let mut names: Vec<String> = artifact["entries"]
        .as_array()
        .expect("actor identifier entries")
        .iter()
        .map(|row| {
            row["id"]
                .as_str()
                .expect("actor identifier entry id")
                .to_owned()
        })
        .collect();
    names.sort();
    names.dedup();
    let variants: Vec<_> =
        names
            .iter()
            .map(|name| {
                format_ident!(
                    "{}",
                    crate::actor_components::camel(name.strip_prefix("minecraft:").unwrap_or_else(
                        || panic!("actor {name} is not in the minecraft namespace")
                    ))
                )
            })
            .collect();
    let tokens = quote! {
        /// Every actor identifier in the captured BDS actor identifier list,
        /// in identifier order.
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
        pub enum ActorType {
            #(#[doc = #names] #variants,)*
        }

        impl ActorType {
            pub const ALL: &'static [ActorType] = &[#(Self::#variants),*];

            /// The namespaced identifier, e.g. `minecraft:chicken`.
            pub const fn name(self) -> &'static str {
                match self {
                    #(Self::#variants => #names,)*
                }
            }

            pub fn from_name(name: &str) -> Option<Self> {
                Some(match name {
                    #(#names => Self::#variants,)*
                    _ => return None,
                })
            }
        }
    };
    let file = syn::parse2::<syn::File>(tokens).expect("generated actor types parse");
    let source = format!(
        "// @generated by crates/unastar-data/build/actor_types.rs from\n\
         // output/actor_identifiers.json. Do not edit.\n\n{}",
        prettyplease::unparse(&file)
    );
    std::fs::write(out.join("actor_types.rs"), source).expect("writing actor types");
}
